const control_ir = @import("control_ir");
const std = @import("std");

/// Implementation ceiling for one compiler-known executable definition.
/// The active source program may lower this through `compiler_limits`.
pub const maximum_executable_definition_operands: usize =
    (control_ir.CompilerLimits{}).maximum_values;

/// Compiler classifications for generated continuation constructors.
pub const ConstructorKind = enum {
    entry,
    segment_entry,
    loop_header,
    await_effect,
    call_return,
    after_handler,
    caller_fuel_yield,
    terminal_handoff,
};

/// Whether a constructor enters a Control IR block or persists a suspension.
pub const ConstructorOrigin = enum {
    block_entry,
    call_entry,
    suspension,
};

/// The exact Control IR edge that created one persisted block entry.
pub const IncomingEdgeKind = enum {
    jump,
    branch_then,
    branch_else,
    call,
    suspension_continuation,
};

/// One compiler-only mapping from a Control IR edge to its canonical RNF
/// continuation constructor.
pub const EntryTransition = struct {
    source_block: control_ir.BlockId,
    edge_kind: IncomingEdgeKind,
    target_block: control_ir.BlockId,
    constructor_id: u32,
};

/// One exact ordered field in a continuation environment.
pub const EnvironmentField = struct {
    value: control_ir.ValueId,
    value_type: control_ir.ValueType,
};

/// Target-neutral relations admitted by the local integer-predicate algebra.
pub const IntegerRelation = enum {
    equal,
    not_equal,
    less_than,
    less_equal,
    greater_than,
    greater_equal,
};

/// Pure Boolean operations retained only as constructor-local equations.
pub const BooleanBinaryOperation = enum {
    @"and",
    @"or",
};

/// Pure fixed-width integer operations retained as local definitions.
pub const IntegerUnaryOperation = enum {
    negate,
    bit_not,
};

/// Pure fixed-width integer operations retained as local definitions.
pub const IntegerBinaryOperation = enum {
    add,
    subtract,
    multiply,
    divide,
    remainder,
    bit_and,
    bit_or,
    bit_xor,
};

/// Bounded constructor-local path facts generated by the compiler.
pub const InvariantTerm = union(enum) {
    boolean: struct {
        value: control_ir.ValueId,
        expected: bool,
    },
    boolean_copy: struct {
        result: control_ir.ValueId,
        source: control_ir.ValueId,
    },
    boolean_not: struct {
        result: control_ir.ValueId,
        operand: control_ir.ValueId,
    },
    boolean_binary: struct {
        result: control_ir.ValueId,
        left: control_ir.ValueId,
        right: control_ir.ValueId,
        operation: BooleanBinaryOperation,
    },
    boolean_select: struct {
        result: control_ir.ValueId,
        condition: control_ir.ValueId,
        then_value: control_ir.ValueId,
        else_value: control_ir.ValueId,
    },
    value_copy: struct {
        result: control_ir.ValueId,
        source: control_ir.ValueId,
    },
    value_constant: struct {
        result: control_ir.ValueId,
        contents: InvariantValue,
    },
    value_select: struct {
        result: control_ir.ValueId,
        condition: control_ir.ValueId,
        then_value: control_ir.ValueId,
        else_value: control_ir.ValueId,
    },
    instruction_result: struct {
        result: control_ir.ValueId,
        definition: control_ir.ValueId,
        operand_count: u8,
        operands: [maximum_executable_definition_operands]control_ir.ValueId,
    },
    product_extract_result: struct {
        result: control_ir.ValueId,
        product: control_ir.ValueId,
        field_index: u16,
    },
    sum_extract_result: struct {
        result: control_ir.ValueId,
        sum: control_ir.ValueId,
        case_index: u16,
    },
    bounded_length_result: struct {
        result: control_ir.ValueId,
        bounded: control_ir.ValueId,
    },
    integer_unary_result: struct {
        result: control_ir.ValueId,
        operand: control_ir.ValueId,
        operation: IntegerUnaryOperation,
        scalar_type: control_ir.ScalarType,
    },
    integer_binary_result: struct {
        result: control_ir.ValueId,
        left: control_ir.ValueId,
        right: control_ir.ValueId,
        operation: IntegerBinaryOperation,
        scalar_type: control_ir.ScalarType,
    },
    integer_convert_result: struct {
        result: control_ir.ValueId,
        operand: control_ir.ValueId,
        scalar_type: control_ir.ScalarType,
    },
    integer_zero: struct {
        value: control_ir.ValueId,
        equal: bool,
    },
    integer_zero_result: struct {
        result: control_ir.ValueId,
        value: control_ir.ValueId,
    },
    integer_relation: struct {
        left: control_ir.ValueId,
        right: control_ir.ValueId,
        relation: IntegerRelation,
        expected: bool,
    },
    integer_relation_result: struct {
        result: control_ir.ValueId,
        left: control_ir.ValueId,
        right: control_ir.ValueId,
        relation: IntegerRelation,
    },
    sum_case: struct {
        value: control_ir.ValueId,
        case_index: u16,
        equal: bool,
    },
    sum_case_result: struct {
        result: control_ir.ValueId,
        value: control_ir.ValueId,
        case_index: u16,
    },

    fn definitionResult(self: InvariantTerm) ?control_ir.ValueId {
        return switch (self) {
            .boolean_copy => |term| term.result,
            .boolean_not => |term| term.result,
            .boolean_binary => |term| term.result,
            .boolean_select => |term| term.result,
            .value_copy => |term| term.result,
            .value_constant => |term| term.result,
            .value_select => |term| term.result,
            .instruction_result => |term| term.result,
            .product_extract_result => |term| term.result,
            .sum_extract_result => |term| term.result,
            .bounded_length_result => |term| term.result,
            .integer_unary_result => |term| term.result,
            .integer_binary_result => |term| term.result,
            .integer_convert_result => |term| term.result,
            .integer_zero_result => |term| term.result,
            .integer_relation_result => |term| term.result,
            .sum_case_result => |term| term.result,
            .boolean,
            .integer_zero,
            .integer_relation,
            .sum_case,
            => null,
        };
    }

    fn addDefinitionInputs(
        self: InvariantTerm,
        required: anytype,
    ) bool {
        var changed = false;
        switch (self) {
            .boolean_copy => |term| {
                changed = required.insert(term.source) or changed;
            },
            .boolean_not => |term| {
                changed = required.insert(term.operand) or changed;
            },
            .boolean_binary => |term| {
                changed = required.insert(term.left) or changed;
                changed = required.insert(term.right) or changed;
            },
            .boolean_select => |term| {
                changed = required.insert(term.condition) or changed;
                changed = required.insert(term.then_value) or changed;
                changed = required.insert(term.else_value) or changed;
            },
            .value_copy => |term| {
                changed = required.insert(term.source) or changed;
            },
            .value_constant => {},
            .instruction_result => |term| {
                for (term.operands[0..term.operand_count]) |operand| {
                    changed = required.insert(operand) or changed;
                }
            },
            .value_select => |term| {
                changed = required.insert(term.condition) or changed;
                changed = required.insert(term.then_value) or changed;
                changed = required.insert(term.else_value) or changed;
            },
            .product_extract_result => |term| {
                changed = required.insert(term.product) or changed;
            },
            .sum_extract_result => |term| {
                changed = required.insert(term.sum) or changed;
            },
            .bounded_length_result => |term| {
                changed = required.insert(term.bounded) or changed;
            },
            .integer_unary_result => |term| {
                changed = required.insert(term.operand) or changed;
            },
            .integer_binary_result => |term| {
                changed = required.insert(term.left) or changed;
                changed = required.insert(term.right) or changed;
            },
            .integer_convert_result => |term| {
                changed = required.insert(term.operand) or changed;
            },
            .integer_zero_result => |term| {
                changed = required.insert(term.value) or changed;
            },
            .integer_relation_result => |term| {
                changed = required.insert(term.left) or changed;
                changed = required.insert(term.right) or changed;
            },
            .sum_case_result => |term| {
                changed = required.insert(term.value) or changed;
            },
            .boolean,
            .integer_zero,
            .integer_relation,
            .sum_case,
            => {},
        }
        return changed;
    }

    fn addRequired(self: InvariantTerm, required: anytype) void {
        switch (self) {
            .boolean => |term| _ = required.insert(term.value),
            .boolean_copy => |term| {
                _ = required.insert(term.result);
                _ = required.insert(term.source);
            },
            .boolean_not => |term| {
                _ = required.insert(term.result);
                _ = required.insert(term.operand);
            },
            .boolean_binary => |term| {
                _ = required.insert(term.result);
                _ = required.insert(term.left);
                _ = required.insert(term.right);
            },
            .boolean_select => |term| {
                _ = required.insert(term.result);
                _ = required.insert(term.condition);
                _ = required.insert(term.then_value);
                _ = required.insert(term.else_value);
            },
            .instruction_result => |term| {
                _ = required.insert(term.result);
                for (term.operands[0..term.operand_count]) |operand| {
                    _ = required.insert(operand);
                }
            },
            .value_copy => |term| {
                _ = required.insert(term.result);
                _ = required.insert(term.source);
            },
            .value_constant => |term| _ = required.insert(term.result),
            .value_select => |term| {
                _ = required.insert(term.result);
                _ = required.insert(term.condition);
                _ = required.insert(term.then_value);
                _ = required.insert(term.else_value);
            },
            .product_extract_result => |term| {
                _ = required.insert(term.result);
                _ = required.insert(term.product);
            },
            .sum_extract_result => |term| {
                _ = required.insert(term.result);
                _ = required.insert(term.sum);
            },
            .bounded_length_result => |term| {
                _ = required.insert(term.result);
                _ = required.insert(term.bounded);
            },
            .integer_unary_result => |term| {
                _ = required.insert(term.result);
                _ = required.insert(term.operand);
            },
            .integer_binary_result => |term| {
                _ = required.insert(term.result);
                _ = required.insert(term.left);
                _ = required.insert(term.right);
            },
            .integer_convert_result => |term| {
                _ = required.insert(term.result);
                _ = required.insert(term.operand);
            },
            .integer_zero => |term| _ = required.insert(term.value),
            .integer_zero_result => |term| {
                _ = required.insert(term.result);
                _ = required.insert(term.value);
            },
            .integer_relation => |term| {
                _ = required.insert(term.left);
                _ = required.insert(term.right);
            },
            .integer_relation_result => |term| {
                _ = required.insert(term.result);
                _ = required.insert(term.left);
                _ = required.insert(term.right);
            },
            .sum_case => |term| _ = required.insert(term.value),
            .sum_case_result => |term| {
                _ = required.insert(term.result);
                _ = required.insert(term.value);
            },
        }
    }

    fn eql(self: InvariantTerm, other: InvariantTerm) bool {
        return switch (self) {
            .boolean => |term| switch (other) {
                .boolean => |other_term| term.value == other_term.value and
                    term.expected == other_term.expected,
                else => false,
            },
            .boolean_copy => |term| switch (other) {
                .boolean_copy => |other_term| term.result == other_term.result and
                    term.source == other_term.source,
                else => false,
            },
            .boolean_not => |term| switch (other) {
                .boolean_not => |other_term| term.result == other_term.result and
                    term.operand == other_term.operand,
                else => false,
            },
            .boolean_binary => |term| switch (other) {
                .boolean_binary => |other_term| term.result == other_term.result and
                    term.left == other_term.left and
                    term.right == other_term.right and
                    term.operation == other_term.operation,
                else => false,
            },
            .boolean_select => |term| switch (other) {
                .boolean_select => |other_term| term.result == other_term.result and
                    term.condition == other_term.condition and
                    term.then_value == other_term.then_value and
                    term.else_value == other_term.else_value,
                else => false,
            },
            .value_copy => |term| switch (other) {
                .value_copy => |other_term| term.result == other_term.result and
                    term.source == other_term.source,
                else => false,
            },
            .value_constant => |term| switch (other) {
                .value_constant => |other_term| term.result == other_term.result and
                    invariantValueEql(term.contents, other_term.contents),
                else => false,
            },
            .value_select => |term| switch (other) {
                .value_select => |other_term| term.result == other_term.result and
                    term.condition == other_term.condition and
                    term.then_value == other_term.then_value and
                    term.else_value == other_term.else_value,
                else => false,
            },
            .instruction_result => |term| switch (other) {
                .instruction_result => |other_term| term.result ==
                    other_term.result and
                    term.definition == other_term.definition and
                    term.operand_count == other_term.operand_count and
                    std.mem.eql(
                        control_ir.ValueId,
                        term.operands[0..term.operand_count],
                        other_term.operands[0..other_term.operand_count],
                    ),
                else => false,
            },
            .product_extract_result => |term| switch (other) {
                .product_extract_result => |other_term| term.result == other_term.result and
                    term.product == other_term.product and
                    term.field_index == other_term.field_index,
                else => false,
            },
            .sum_extract_result => |term| switch (other) {
                .sum_extract_result => |other_term| term.result == other_term.result and
                    term.sum == other_term.sum and
                    term.case_index == other_term.case_index,
                else => false,
            },
            .bounded_length_result => |term| switch (other) {
                .bounded_length_result => |other_term| term.result == other_term.result and
                    term.bounded == other_term.bounded,
                else => false,
            },
            .integer_unary_result => |term| switch (other) {
                .integer_unary_result => |other_term| term.result == other_term.result and
                    term.operand == other_term.operand and
                    term.operation == other_term.operation and
                    term.scalar_type == other_term.scalar_type,
                else => false,
            },
            .integer_binary_result => |term| switch (other) {
                .integer_binary_result => |other_term| term.result == other_term.result and
                    term.left == other_term.left and
                    term.right == other_term.right and
                    term.operation == other_term.operation and
                    term.scalar_type == other_term.scalar_type,
                else => false,
            },
            .integer_convert_result => |term| switch (other) {
                .integer_convert_result => |other_term| term.result == other_term.result and
                    term.operand == other_term.operand and
                    term.scalar_type == other_term.scalar_type,
                else => false,
            },
            .integer_zero => |term| switch (other) {
                .integer_zero => |other_term| term.value == other_term.value and
                    term.equal == other_term.equal,
                else => false,
            },
            .integer_zero_result => |term| switch (other) {
                .integer_zero_result => |other_term| term.result == other_term.result and
                    term.value == other_term.value,
                else => false,
            },
            .integer_relation => |term| switch (other) {
                .integer_relation => |other_term| term.left == other_term.left and
                    term.right == other_term.right and
                    term.relation == other_term.relation and
                    term.expected == other_term.expected,
                else => false,
            },
            .integer_relation_result => |term| switch (other) {
                .integer_relation_result => |other_term| term.result == other_term.result and
                    term.left == other_term.left and
                    term.right == other_term.right and
                    term.relation == other_term.relation,
                else => false,
            },
            .sum_case => |term| switch (other) {
                .sum_case => |other_term| term.value == other_term.value and
                    term.case_index == other_term.case_index and
                    term.equal == other_term.equal,
                else => false,
            },
            .sum_case_result => |term| switch (other) {
                .sum_case_result => |other_term| term.result == other_term.result and
                    term.value == other_term.value and
                    term.case_index == other_term.case_index,
                else => false,
            },
        };
    }
};

/// Minimal target-neutral values needed to evaluate the invariant algebra.
pub const InvariantValue = union(enum) {
    boolean: bool,
    signed: i64,
    unsigned: u64,
    sum_case: u16,
};

fn invariantValueEql(left: InvariantValue, right: InvariantValue) bool {
    return switch (left) {
        .boolean => |value| switch (right) {
            .boolean => |other| value == other,
            else => false,
        },
        .signed => |value| switch (right) {
            .signed => |other| value == other,
            else => false,
        },
        .unsigned => |value| switch (right) {
            .unsigned => |other| value == other,
            else => false,
        },
        .sum_case => |value| switch (right) {
            .sum_case => |other| value == other,
            else => false,
        },
    };
}

fn invariantValueLessThan(left: InvariantValue, right: InvariantValue) bool {
    const left_tag = @intFromEnum(std.meta.activeTag(left));
    const right_tag = @intFromEnum(std.meta.activeTag(right));
    if (left_tag != right_tag) return left_tag < right_tag;
    return switch (left) {
        .boolean => |value| @intFromBool(value) < @intFromBool(right.boolean),
        .signed => |value| value < right.signed,
        .unsigned => |value| value < right.unsigned,
        .sum_case => |value| value < right.sum_case,
    };
}

/// One value binding supplied to constructor-local invariant evaluation.
pub const InvariantBinding = struct {
    value: control_ir.ValueId,
    contents: InvariantValue,
};

/// RNF synthesis and local-validation failures.
pub const Error = control_ir.ValidationError || error{
    TooManyConstructors,
    TooManyEnvironmentFields,
    TooManyInvariantTerms,
    MissingInvariantValue,
    InvalidInvariantValue,
    InvariantViolation,
    PathFactsDidNotConverge,
    UnsupportedInvariantDefinition,
};

fn bindingFor(
    bindings: []const InvariantBinding,
    value: control_ir.ValueId,
) ?InvariantValue {
    for (bindings) |binding| {
        if (binding.value == value) return binding.contents;
    }
    return null;
}

fn booleanBinding(
    bindings: []const InvariantBinding,
    value: control_ir.ValueId,
) Error!bool {
    return switch (bindingFor(bindings, value) orelse
        return error.MissingInvariantValue) {
        .boolean => |actual| actual,
        .signed, .unsigned, .sum_case => error.InvalidInvariantValue,
    };
}

/// Evaluate one admitted fixed-width integer relation.
pub fn integerRelationHolds(
    left: anytype,
    right: @TypeOf(left),
    relation: IntegerRelation,
) bool {
    return switch (relation) {
        .equal => left == right,
        .not_equal => left != right,
        .less_than => left < right,
        .less_equal => left <= right,
        .greater_than => left > right,
        .greater_equal => left >= right,
    };
}

/// Validate one successful fixed-width integer unary definition without traps.
pub fn integerUnaryDefinitionHolds(
    result: anytype,
    operand: @TypeOf(result),
    operation: IntegerUnaryOperation,
) bool {
    const T = @TypeOf(result);
    const expected = switch (operation) {
        .negate => std.math.sub(T, 0, operand) catch return false,
        .bit_not => ~operand,
    };
    return result == expected;
}

/// Validate one successful fixed-width integer binary definition without traps.
pub fn integerBinaryDefinitionHolds(
    result: anytype,
    left: @TypeOf(result),
    right: @TypeOf(result),
    operation: IntegerBinaryOperation,
) bool {
    const T = @TypeOf(result);
    const expected = switch (operation) {
        .add => std.math.add(T, left, right) catch return false,
        .subtract => std.math.sub(T, left, right) catch return false,
        .multiply => std.math.mul(T, left, right) catch return false,
        .divide => blk: {
            if (right == 0) return false;
            if (comptime @typeInfo(T).int.signedness == .signed) {
                if (left == std.math.minInt(T) and right == -1) return false;
            }
            break :blk @divTrunc(left, right);
        },
        .remainder => blk: {
            if (right == 0) return false;
            if (comptime @typeInfo(T).int.signedness == .signed) {
                if (left == std.math.minInt(T) and right == -1) return false;
            }
            break :blk @rem(left, right);
        },
        .bit_and => left & right,
        .bit_or => left | right,
        .bit_xor => left ^ right,
    };
    return result == expected;
}

/// Validate one successful checked fixed-width integer conversion.
pub fn integerConvertDefinitionHolds(result: anytype, operand: anytype) bool {
    const expected = std.math.cast(@TypeOf(result), operand) orelse return false;
    return result == expected;
}

fn invariantIntegerAs(comptime T: type, value: InvariantValue) ?T {
    return switch (value) {
        .signed => |contents| std.math.cast(T, contents),
        .unsigned => |contents| std.math.cast(T, contents),
        .boolean, .sum_case => null,
    };
}

fn integerUnaryInvariantHolds(
    result: InvariantValue,
    operand: InvariantValue,
    operation: IntegerUnaryOperation,
    scalar_type: control_ir.ScalarType,
) bool {
    return switch (scalar_type) {
        .i8 => integerUnaryDefinitionHolds(
            invariantIntegerAs(i8, result) orelse return false,
            invariantIntegerAs(i8, operand) orelse return false,
            operation,
        ),
        .i16 => integerUnaryDefinitionHolds(
            invariantIntegerAs(i16, result) orelse return false,
            invariantIntegerAs(i16, operand) orelse return false,
            operation,
        ),
        .i32 => integerUnaryDefinitionHolds(
            invariantIntegerAs(i32, result) orelse return false,
            invariantIntegerAs(i32, operand) orelse return false,
            operation,
        ),
        .i64 => integerUnaryDefinitionHolds(
            invariantIntegerAs(i64, result) orelse return false,
            invariantIntegerAs(i64, operand) orelse return false,
            operation,
        ),
        .u8 => integerUnaryDefinitionHolds(
            invariantIntegerAs(u8, result) orelse return false,
            invariantIntegerAs(u8, operand) orelse return false,
            operation,
        ),
        .u16 => integerUnaryDefinitionHolds(
            invariantIntegerAs(u16, result) orelse return false,
            invariantIntegerAs(u16, operand) orelse return false,
            operation,
        ),
        .u32 => integerUnaryDefinitionHolds(
            invariantIntegerAs(u32, result) orelse return false,
            invariantIntegerAs(u32, operand) orelse return false,
            operation,
        ),
        .u64 => integerUnaryDefinitionHolds(
            invariantIntegerAs(u64, result) orelse return false,
            invariantIntegerAs(u64, operand) orelse return false,
            operation,
        ),
        .unit, .boolean => false,
    };
}

fn integerBinaryInvariantHolds(
    result: InvariantValue,
    left: InvariantValue,
    right: InvariantValue,
    operation: IntegerBinaryOperation,
    scalar_type: control_ir.ScalarType,
) bool {
    return switch (scalar_type) {
        inline .i8, .i16, .i32, .i64, .u8, .u16, .u32, .u64 => |tag| blk: {
            const T = switch (tag) {
                .i8 => i8,
                .i16 => i16,
                .i32 => i32,
                .i64 => i64,
                .u8 => u8,
                .u16 => u16,
                .u32 => u32,
                .u64 => u64,
                else => unreachable,
            };
            break :blk integerBinaryDefinitionHolds(
                invariantIntegerAs(T, result) orelse return false,
                invariantIntegerAs(T, left) orelse return false,
                invariantIntegerAs(T, right) orelse return false,
                operation,
            );
        },
        .unit, .boolean => false,
    };
}

fn integerConvertInvariantHolds(
    result: InvariantValue,
    operand: InvariantValue,
    scalar_type: control_ir.ScalarType,
) bool {
    return switch (scalar_type) {
        inline .i8, .i16, .i32, .i64, .u8, .u16, .u32, .u64 => |tag| blk: {
            const T = switch (tag) {
                .i8 => i8,
                .i16 => i16,
                .i32 => i32,
                .i64 => i64,
                .u8 => u8,
                .u16 => u16,
                .u32 => u32,
                .u64 => u64,
                else => unreachable,
            };
            const expected = invariantIntegerAs(T, operand) orelse return false;
            break :blk invariantIntegerAs(T, result) == expected;
        },
        .unit, .boolean => false,
    };
}

fn evaluate(term: InvariantTerm, bindings: []const InvariantBinding) Error!void {
    const accepted = switch (term) {
        .boolean => |predicate| switch (bindingFor(
            bindings,
            predicate.value,
        ) orelse return error.MissingInvariantValue) {
            .boolean => |actual| actual == predicate.expected,
            .signed, .unsigned, .sum_case => return error.InvalidInvariantValue,
        },
        .boolean_copy => |definition| try booleanBinding(
            bindings,
            definition.result,
        ) == try booleanBinding(bindings, definition.source),
        .boolean_not => |definition| try booleanBinding(
            bindings,
            definition.result,
        ) == !try booleanBinding(bindings, definition.operand),
        .boolean_binary => |definition| blk: {
            const left = try booleanBinding(bindings, definition.left);
            const right = try booleanBinding(bindings, definition.right);
            const expected = switch (definition.operation) {
                .@"and" => left and right,
                .@"or" => left or right,
            };
            break :blk try booleanBinding(bindings, definition.result) ==
                expected;
        },
        .boolean_select => |definition| blk: {
            const selected = if (try booleanBinding(
                bindings,
                definition.condition,
            ))
                try booleanBinding(bindings, definition.then_value)
            else
                try booleanBinding(bindings, definition.else_value);
            break :blk try booleanBinding(bindings, definition.result) ==
                selected;
        },
        .value_copy => |definition| invariantValueEql(
            bindingFor(bindings, definition.result) orelse
                return error.MissingInvariantValue,
            bindingFor(bindings, definition.source) orelse
                return error.MissingInvariantValue,
        ),
        .value_constant => |definition| invariantValueEql(
            bindingFor(bindings, definition.result) orelse
                return error.MissingInvariantValue,
            definition.contents,
        ),
        .value_select => |definition| invariantValueEql(
            bindingFor(bindings, definition.result) orelse
                return error.MissingInvariantValue,
            bindingFor(
                bindings,
                if (try booleanBinding(bindings, definition.condition))
                    definition.then_value
                else
                    definition.else_value,
            ) orelse return error.MissingInvariantValue,
        ),
        .product_extract_result,
        .sum_extract_result,
        .bounded_length_result,
        .instruction_result,
        => return error.InvalidInvariantValue,
        .integer_unary_result => |definition| integerUnaryInvariantHolds(
            bindingFor(bindings, definition.result) orelse
                return error.MissingInvariantValue,
            bindingFor(bindings, definition.operand) orelse
                return error.MissingInvariantValue,
            definition.operation,
            definition.scalar_type,
        ),
        .integer_binary_result => |definition| integerBinaryInvariantHolds(
            bindingFor(bindings, definition.result) orelse
                return error.MissingInvariantValue,
            bindingFor(bindings, definition.left) orelse
                return error.MissingInvariantValue,
            bindingFor(bindings, definition.right) orelse
                return error.MissingInvariantValue,
            definition.operation,
            definition.scalar_type,
        ),
        .integer_convert_result => |definition| integerConvertInvariantHolds(
            bindingFor(bindings, definition.result) orelse
                return error.MissingInvariantValue,
            bindingFor(bindings, definition.operand) orelse
                return error.MissingInvariantValue,
            definition.scalar_type,
        ),
        .integer_zero => |predicate| switch (bindingFor(
            bindings,
            predicate.value,
        ) orelse return error.MissingInvariantValue) {
            .boolean, .sum_case => return error.InvalidInvariantValue,
            .signed => |actual| (actual == 0) == predicate.equal,
            .unsigned => |actual| (actual == 0) == predicate.equal,
        },
        .integer_zero_result => |definition| blk: {
            const expected = switch (bindingFor(
                bindings,
                definition.value,
            ) orelse return error.MissingInvariantValue) {
                .boolean, .sum_case => return error.InvalidInvariantValue,
                .signed => |actual| actual == 0,
                .unsigned => |actual| actual == 0,
            };
            break :blk try booleanBinding(bindings, definition.result) ==
                expected;
        },
        .integer_relation => |predicate| blk: {
            const left = bindingFor(bindings, predicate.left) orelse
                return error.MissingInvariantValue;
            const right = bindingFor(bindings, predicate.right) orelse
                return error.MissingInvariantValue;
            const actual = switch (left) {
                .boolean, .sum_case => return error.InvalidInvariantValue,
                .signed => |left_value| switch (right) {
                    .signed => |right_value| integerRelationHolds(
                        left_value,
                        right_value,
                        predicate.relation,
                    ),
                    .boolean, .unsigned, .sum_case => return error.InvalidInvariantValue,
                },
                .unsigned => |left_value| switch (right) {
                    .unsigned => |right_value| integerRelationHolds(
                        left_value,
                        right_value,
                        predicate.relation,
                    ),
                    .boolean, .signed, .sum_case => return error.InvalidInvariantValue,
                },
            };
            break :blk actual == predicate.expected;
        },
        .integer_relation_result => |definition| blk: {
            const left = bindingFor(bindings, definition.left) orelse
                return error.MissingInvariantValue;
            const right = bindingFor(bindings, definition.right) orelse
                return error.MissingInvariantValue;
            const expected = switch (left) {
                .boolean, .sum_case => return error.InvalidInvariantValue,
                .signed => |left_value| switch (right) {
                    .signed => |right_value| integerRelationHolds(
                        left_value,
                        right_value,
                        definition.relation,
                    ),
                    .boolean, .unsigned, .sum_case => return error.InvalidInvariantValue,
                },
                .unsigned => |left_value| switch (right) {
                    .unsigned => |right_value| integerRelationHolds(
                        left_value,
                        right_value,
                        definition.relation,
                    ),
                    .boolean, .signed, .sum_case => return error.InvalidInvariantValue,
                },
            };
            break :blk try booleanBinding(bindings, definition.result) ==
                expected;
        },
        .sum_case => |predicate| switch (bindingFor(
            bindings,
            predicate.value,
        ) orelse return error.MissingInvariantValue) {
            .sum_case => |actual| (actual == predicate.case_index) ==
                predicate.equal,
            .boolean, .signed, .unsigned => return error.InvalidInvariantValue,
        },
        .sum_case_result => |definition| blk: {
            const actual = switch (bindingFor(
                bindings,
                definition.value,
            ) orelse return error.MissingInvariantValue) {
                .sum_case => |case_index| case_index,
                .boolean, .signed, .unsigned => return error.InvalidInvariantValue,
            };
            break :blk try booleanBinding(bindings, definition.result) ==
                (actual == definition.case_index);
        },
    };
    if (!accepted) return error.InvariantViolation;
}

/// One bounded program-specific continuation constructor.
pub fn Constructor(
    comptime maximum_environment_fields: usize,
    comptime maximum_invariant_terms: usize,
) type {
    return struct {
        const Self = @This();

        id: u32,
        kind: ConstructorKind,
        origin: ConstructorOrigin,
        source_block: control_ir.BlockId,
        resume_target: ?control_ir.BlockId = null,
        has_activation_context: bool = false,
        activation: [maximum_environment_fields]EnvironmentField = undefined,
        activation_len: usize = 0,
        environment: [maximum_environment_fields]EnvironmentField = undefined,
        environment_len: usize = 0,
        invariants: [maximum_invariant_terms]InvariantTerm = undefined,
        invariant_len: usize = 0,

        /// Borrow the exact ordered environment schema.
        pub fn environmentFields(self: *const Self) []const EnvironmentField {
            return self.environment[0..self.environment_len];
        }

        /// Borrow the immutable invocation values retained for a non-root frame.
        pub fn activationFields(self: *const Self) []const EnvironmentField {
            return self.activation[0..self.activation_len];
        }

        /// Borrow the constructor-local invariant conjunction.
        pub fn invariantTerms(self: *const Self) []const InvariantTerm {
            return self.invariants[0..self.invariant_len];
        }

        /// Validate only the bounded local path facts attached to this constructor.
        pub fn validateInvariant(
            self: *const Self,
            bindings: []const InvariantBinding,
        ) Error!void {
            for (self.invariantTerms()) |term| try evaluate(term, bindings);
        }
    };
}

fn constructorKindForRole(role: control_ir.BlockRole) ConstructorKind {
    return switch (role) {
        .segment => .segment_entry,
        .loop_header => .loop_header,
        .call_return => .call_return,
        .after_handler => .after_handler,
        .terminal_handoff => .terminal_handoff,
    };
}

fn constructorKindForSuspension(
    kind: control_ir.SuspensionKind,
) ConstructorKind {
    return switch (kind) {
        .effect => .await_effect,
        .call => .call_return,
        .explicit_yield, .caller_fuel => .caller_fuel_yield,
    };
}

fn edgeTargets(edge: control_ir.Edge, target: control_ir.BlockId) bool {
    return edge.target == target;
}

fn definingInstruction(
    program: control_ir.Program,
    value: control_ir.ValueId,
) ?control_ir.Instruction {
    for (program.blocks) |block| {
        for (block.instructions) |instruction| {
            if (instruction.result == value) return instruction;
        }
    }
    return null;
}

fn directFactForValue(
    program: control_ir.Program,
    condition: control_ir.ValueId,
    expected: bool,
    remaining_depth: usize,
) ?InvariantTerm {
    if (remaining_depth == 0) return null;
    if (definingInstruction(program, condition)) |instruction| {
        switch (instruction.operation) {
            .copy => return directFactForValue(
                program,
                instruction.operands[0],
                expected,
                remaining_depth - 1,
            ),
            .boolean_not => return directFactForValue(
                program,
                instruction.operands[0],
                !expected,
                remaining_depth - 1,
            ),
            else => {},
        }
        if (instruction.kind == .compare_eq_zero and instruction.operands.len == 1) {
            return .{ .integer_zero = .{
                .value = instruction.operands[0],
                .equal = expected,
            } };
        }
        switch (instruction.operation) {
            .integer_equal,
            .integer_not_equal,
            .integer_less_than,
            .integer_less_equal,
            .integer_greater_than,
            .integer_greater_equal,
            => return .{ .integer_relation = .{
                .left = instruction.operands[0],
                .right = instruction.operands[1],
                .relation = switch (instruction.operation) {
                    .integer_equal => .equal,
                    .integer_not_equal => .not_equal,
                    .integer_less_than => .less_than,
                    .integer_less_equal => .less_equal,
                    .integer_greater_than => .greater_than,
                    .integer_greater_equal => .greater_equal,
                    else => unreachable,
                },
                .expected = expected,
            } },
            .sum_tag_is => |case_index| return .{ .sum_case = .{
                .value = instruction.operands[0],
                .case_index = case_index,
                .equal = expected,
            } },
            .optional_is_some => return .{ .sum_case = .{
                .value = instruction.operands[0],
                .case_index = 1,
                .equal = expected,
            } },
            else => {},
        }
    }
    return null;
}

fn factForBranch(
    program: control_ir.Program,
    branch: control_ir.Branch,
    expected: bool,
) ?InvariantTerm {
    if (directFactForValue(
        program,
        branch.condition,
        expected,
        program.value_types.len + 1,
    )) |fact| return fact;
    return .{ .boolean = .{
        .value = branch.condition,
        .expected = expected,
    } };
}

/// One bounded compiler result containing canonical dense constructors.
pub fn NormalForm(
    comptime maximum_values: usize,
    comptime maximum_blocks: usize,
    comptime maximum_constructors: usize,
    comptime maximum_environment_fields: usize,
    comptime maximum_invariant_terms: usize,
) type {
    const Set = control_ir.ValueSet(maximum_values);
    const ConstructorType = Constructor(
        maximum_environment_fields,
        maximum_invariant_terms,
    );
    const Liveness = control_ir.Liveness(maximum_values, maximum_blocks);
    const ReachabilityType = control_ir.Reachability(maximum_blocks);
    const CanonicalValues = struct {
        values: [maximum_values]control_ir.ValueId = undefined,
        present: [maximum_values]bool =
            [_]bool{false} ** maximum_values,
        len: usize = 0,

        fn bind(self: *@This(), value: control_ir.ValueId) void {
            if (self.present[@intCast(value)]) return;
            self.present[@intCast(value)] = true;
            self.values[self.len] = value;
            self.len += 1;
        }

        fn analyze(
            program: control_ir.Program,
            reachability: ReachabilityType,
        ) @This() {
            var result: @This() = .{};
            for (0..reachability.count) |dense_block_index| {
                const source_block = reachability.sourceId(
                    @intCast(dense_block_index),
                ) orelse unreachable;
                const block = program.blocks[@intCast(source_block)];
                for (block.parameters) |parameter| result.bind(parameter);
                for (block.instructions) |instruction| {
                    result.bind(instruction.result);
                }
            }
            return result;
        }

        fn ordinal(
            self: @This(),
            value: control_ir.ValueId,
        ) usize {
            for (self.values[0..self.len], 0..) |candidate, index| {
                if (candidate == value) return index;
            }
            unreachable;
        }
    };
    const FactSet = struct {
        terms: [maximum_invariant_terms]InvariantTerm = undefined,
        len: usize = 0,

        fn contains(self: @This(), term: InvariantTerm) bool {
            for (self.terms[0..self.len]) |existing| {
                if (existing.eql(term)) return true;
            }
            return false;
        }

        fn insert(self: *@This(), term: InvariantTerm) Error!void {
            if (self.contains(term)) return;
            if (comptime maximum_invariant_terms == 0) {
                return error.TooManyInvariantTerms;
            }
            if (self.len == maximum_invariant_terms) {
                return error.TooManyInvariantTerms;
            }
            self.terms[self.len] = term;
            self.len += 1;
        }

        fn intersection(self: @This(), other: @This()) @This() {
            if (comptime maximum_invariant_terms == 0) return .{};
            var result: @This() = .{};
            for (self.terms[0..self.len]) |term| {
                if (!other.contains(term)) continue;
                result.terms[result.len] = term;
                result.len += 1;
            }
            return result;
        }

        fn eql(self: @This(), other: @This()) bool {
            if (self.len != other.len) return false;
            for (self.terms[0..self.len]) |term| {
                if (!other.contains(term)) return false;
            }
            return true;
        }

        fn termLessThan(
            canonical_values: CanonicalValues,
            left: InvariantTerm,
            right: InvariantTerm,
        ) bool {
            const left_tag = @intFromEnum(std.meta.activeTag(left));
            const right_tag = @intFromEnum(std.meta.activeTag(right));
            if (left_tag != right_tag) return left_tag < right_tag;
            return switch (left) {
                .boolean => |left_term| blk: {
                    const right_term = right.boolean;
                    const left_value = canonical_values.ordinal(left_term.value);
                    const right_value = canonical_values.ordinal(right_term.value);
                    if (left_value != right_value) {
                        break :blk left_value < right_value;
                    }
                    break :blk @intFromBool(left_term.expected) <
                        @intFromBool(right_term.expected);
                },
                .boolean_copy => |left_term| blk: {
                    const right_term = right.boolean_copy;
                    const left_result = canonical_values.ordinal(left_term.result);
                    const right_result = canonical_values.ordinal(right_term.result);
                    if (left_result != right_result) {
                        break :blk left_result < right_result;
                    }
                    break :blk canonical_values.ordinal(left_term.source) <
                        canonical_values.ordinal(right_term.source);
                },
                .boolean_not => |left_term| blk: {
                    const right_term = right.boolean_not;
                    const left_result = canonical_values.ordinal(left_term.result);
                    const right_result = canonical_values.ordinal(right_term.result);
                    if (left_result != right_result) {
                        break :blk left_result < right_result;
                    }
                    break :blk canonical_values.ordinal(left_term.operand) <
                        canonical_values.ordinal(right_term.operand);
                },
                .boolean_binary => |left_term| blk: {
                    const right_term = right.boolean_binary;
                    const left_result = canonical_values.ordinal(left_term.result);
                    const right_result = canonical_values.ordinal(right_term.result);
                    if (left_result != right_result) {
                        break :blk left_result < right_result;
                    }
                    const left_left = canonical_values.ordinal(left_term.left);
                    const right_left = canonical_values.ordinal(right_term.left);
                    if (left_left != right_left) {
                        break :blk left_left < right_left;
                    }
                    const left_right = canonical_values.ordinal(left_term.right);
                    const right_right = canonical_values.ordinal(right_term.right);
                    if (left_right != right_right) {
                        break :blk left_right < right_right;
                    }
                    break :blk @intFromEnum(left_term.operation) <
                        @intFromEnum(right_term.operation);
                },
                .boolean_select => |left_term| blk: {
                    const right_term = right.boolean_select;
                    inline for (
                        .{
                            left_term.result,
                            left_term.condition,
                            left_term.then_value,
                            left_term.else_value,
                        },
                        .{
                            right_term.result,
                            right_term.condition,
                            right_term.then_value,
                            right_term.else_value,
                        },
                    ) |left_value, right_value| {
                        const left_ordinal =
                            canonical_values.ordinal(left_value);
                        const right_ordinal =
                            canonical_values.ordinal(right_value);
                        if (left_ordinal != right_ordinal) {
                            break :blk left_ordinal < right_ordinal;
                        }
                    }
                    break :blk false;
                },
                .value_copy => |left_term| blk: {
                    const right_term = right.value_copy;
                    const left_result = canonical_values.ordinal(left_term.result);
                    const right_result = canonical_values.ordinal(right_term.result);
                    if (left_result != right_result) {
                        break :blk left_result < right_result;
                    }
                    break :blk canonical_values.ordinal(left_term.source) <
                        canonical_values.ordinal(right_term.source);
                },
                .value_constant => |left_term| blk: {
                    const right_term = right.value_constant;
                    const left_result = canonical_values.ordinal(left_term.result);
                    const right_result = canonical_values.ordinal(right_term.result);
                    if (left_result != right_result) {
                        break :blk left_result < right_result;
                    }
                    break :blk invariantValueLessThan(
                        left_term.contents,
                        right_term.contents,
                    );
                },
                .value_select => |left_term| blk: {
                    const right_term = right.value_select;
                    inline for (
                        .{
                            left_term.result,
                            left_term.condition,
                            left_term.then_value,
                            left_term.else_value,
                        },
                        .{
                            right_term.result,
                            right_term.condition,
                            right_term.then_value,
                            right_term.else_value,
                        },
                    ) |left_value, right_value| {
                        const left_ordinal = canonical_values.ordinal(left_value);
                        const right_ordinal = canonical_values.ordinal(right_value);
                        if (left_ordinal != right_ordinal) {
                            break :blk left_ordinal < right_ordinal;
                        }
                    }
                    break :blk false;
                },
                .instruction_result => |left_term| blk: {
                    const right_term = right.instruction_result;
                    const left_result = canonical_values.ordinal(left_term.result);
                    const right_result = canonical_values.ordinal(right_term.result);
                    if (left_result != right_result) {
                        break :blk left_result < right_result;
                    }
                    const left_definition = canonical_values.ordinal(
                        left_term.definition,
                    );
                    const right_definition = canonical_values.ordinal(
                        right_term.definition,
                    );
                    if (left_definition != right_definition) {
                        break :blk left_definition < right_definition;
                    }
                    if (left_term.operand_count != right_term.operand_count) {
                        break :blk left_term.operand_count <
                            right_term.operand_count;
                    }
                    for (
                        left_term.operands[0..left_term.operand_count],
                        right_term.operands[0..right_term.operand_count],
                    ) |left_operand, right_operand| {
                        const left_ordinal = canonical_values.ordinal(left_operand);
                        const right_ordinal = canonical_values.ordinal(right_operand);
                        if (left_ordinal != right_ordinal) {
                            break :blk left_ordinal < right_ordinal;
                        }
                    }
                    break :blk false;
                },
                .product_extract_result => |left_term| blk: {
                    const right_term = right.product_extract_result;
                    const left_result = canonical_values.ordinal(left_term.result);
                    const right_result = canonical_values.ordinal(right_term.result);
                    if (left_result != right_result) {
                        break :blk left_result < right_result;
                    }
                    const left_product = canonical_values.ordinal(left_term.product);
                    const right_product = canonical_values.ordinal(right_term.product);
                    if (left_product != right_product) {
                        break :blk left_product < right_product;
                    }
                    break :blk left_term.field_index < right_term.field_index;
                },
                .sum_extract_result => |left_term| blk: {
                    const right_term = right.sum_extract_result;
                    const left_result = canonical_values.ordinal(left_term.result);
                    const right_result = canonical_values.ordinal(right_term.result);
                    if (left_result != right_result) {
                        break :blk left_result < right_result;
                    }
                    const left_sum = canonical_values.ordinal(left_term.sum);
                    const right_sum = canonical_values.ordinal(right_term.sum);
                    if (left_sum != right_sum) {
                        break :blk left_sum < right_sum;
                    }
                    break :blk left_term.case_index < right_term.case_index;
                },
                .bounded_length_result => |left_term| blk: {
                    const right_term = right.bounded_length_result;
                    const left_result = canonical_values.ordinal(left_term.result);
                    const right_result = canonical_values.ordinal(right_term.result);
                    if (left_result != right_result) {
                        break :blk left_result < right_result;
                    }
                    break :blk canonical_values.ordinal(left_term.bounded) <
                        canonical_values.ordinal(right_term.bounded);
                },
                .integer_unary_result => |left_term| blk: {
                    const right_term = right.integer_unary_result;
                    inline for (
                        .{ left_term.result, left_term.operand },
                        .{ right_term.result, right_term.operand },
                    ) |left_value, right_value| {
                        const left_ordinal = canonical_values.ordinal(left_value);
                        const right_ordinal = canonical_values.ordinal(right_value);
                        if (left_ordinal != right_ordinal) {
                            break :blk left_ordinal < right_ordinal;
                        }
                    }
                    const left_operation = @intFromEnum(left_term.operation);
                    const right_operation = @intFromEnum(right_term.operation);
                    if (left_operation != right_operation) {
                        break :blk left_operation < right_operation;
                    }
                    break :blk @intFromEnum(left_term.scalar_type) <
                        @intFromEnum(right_term.scalar_type);
                },
                .integer_binary_result => |left_term| blk: {
                    const right_term = right.integer_binary_result;
                    inline for (
                        .{ left_term.result, left_term.left, left_term.right },
                        .{ right_term.result, right_term.left, right_term.right },
                    ) |left_value, right_value| {
                        const left_ordinal = canonical_values.ordinal(left_value);
                        const right_ordinal = canonical_values.ordinal(right_value);
                        if (left_ordinal != right_ordinal) {
                            break :blk left_ordinal < right_ordinal;
                        }
                    }
                    const left_operation = @intFromEnum(left_term.operation);
                    const right_operation = @intFromEnum(right_term.operation);
                    if (left_operation != right_operation) {
                        break :blk left_operation < right_operation;
                    }
                    break :blk @intFromEnum(left_term.scalar_type) <
                        @intFromEnum(right_term.scalar_type);
                },
                .integer_convert_result => |left_term| blk: {
                    const right_term = right.integer_convert_result;
                    inline for (
                        .{ left_term.result, left_term.operand },
                        .{ right_term.result, right_term.operand },
                    ) |left_value, right_value| {
                        const left_ordinal = canonical_values.ordinal(left_value);
                        const right_ordinal = canonical_values.ordinal(right_value);
                        if (left_ordinal != right_ordinal) {
                            break :blk left_ordinal < right_ordinal;
                        }
                    }
                    break :blk @intFromEnum(left_term.scalar_type) <
                        @intFromEnum(right_term.scalar_type);
                },
                .integer_zero => |left_term| blk: {
                    const right_term = right.integer_zero;
                    const left_value = canonical_values.ordinal(left_term.value);
                    const right_value = canonical_values.ordinal(right_term.value);
                    if (left_value != right_value) {
                        break :blk left_value < right_value;
                    }
                    break :blk @intFromBool(left_term.equal) <
                        @intFromBool(right_term.equal);
                },
                .integer_zero_result => |left_term| blk: {
                    const right_term = right.integer_zero_result;
                    const left_result = canonical_values.ordinal(left_term.result);
                    const right_result = canonical_values.ordinal(right_term.result);
                    if (left_result != right_result) {
                        break :blk left_result < right_result;
                    }
                    break :blk canonical_values.ordinal(left_term.value) <
                        canonical_values.ordinal(right_term.value);
                },
                .integer_relation => |left_term| blk: {
                    const right_term = right.integer_relation;
                    const left_left = canonical_values.ordinal(left_term.left);
                    const right_left = canonical_values.ordinal(right_term.left);
                    if (left_left != right_left) {
                        break :blk left_left < right_left;
                    }
                    const left_right = canonical_values.ordinal(left_term.right);
                    const right_right = canonical_values.ordinal(right_term.right);
                    if (left_right != right_right) {
                        break :blk left_right < right_right;
                    }
                    const left_relation = @intFromEnum(left_term.relation);
                    const right_relation = @intFromEnum(right_term.relation);
                    if (left_relation != right_relation) {
                        break :blk left_relation < right_relation;
                    }
                    break :blk @intFromBool(left_term.expected) <
                        @intFromBool(right_term.expected);
                },
                .integer_relation_result => |left_term| blk: {
                    const right_term = right.integer_relation_result;
                    const left_result = canonical_values.ordinal(left_term.result);
                    const right_result = canonical_values.ordinal(right_term.result);
                    if (left_result != right_result) {
                        break :blk left_result < right_result;
                    }
                    const left_left = canonical_values.ordinal(left_term.left);
                    const right_left = canonical_values.ordinal(right_term.left);
                    if (left_left != right_left) {
                        break :blk left_left < right_left;
                    }
                    const left_right = canonical_values.ordinal(left_term.right);
                    const right_right = canonical_values.ordinal(right_term.right);
                    if (left_right != right_right) {
                        break :blk left_right < right_right;
                    }
                    break :blk @intFromEnum(left_term.relation) <
                        @intFromEnum(right_term.relation);
                },
                .sum_case => |left_term| blk: {
                    const right_term = right.sum_case;
                    const left_value = canonical_values.ordinal(left_term.value);
                    const right_value = canonical_values.ordinal(right_term.value);
                    if (left_value != right_value) {
                        break :blk left_value < right_value;
                    }
                    if (left_term.case_index != right_term.case_index) {
                        break :blk left_term.case_index < right_term.case_index;
                    }
                    break :blk @intFromBool(left_term.equal) <
                        @intFromBool(right_term.equal);
                },
                .sum_case_result => |left_term| blk: {
                    const right_term = right.sum_case_result;
                    const left_result = canonical_values.ordinal(left_term.result);
                    const right_result = canonical_values.ordinal(right_term.result);
                    if (left_result != right_result) {
                        break :blk left_result < right_result;
                    }
                    const left_value = canonical_values.ordinal(left_term.value);
                    const right_value = canonical_values.ordinal(right_term.value);
                    if (left_value != right_value) {
                        break :blk left_value < right_value;
                    }
                    break :blk left_term.case_index < right_term.case_index;
                },
            };
        }

        fn canonicalize(
            self: *@This(),
            canonical_values: CanonicalValues,
        ) void {
            if (comptime maximum_invariant_terms == 0) return;
            var index: usize = 1;
            while (index < self.len) : (index += 1) {
                const term = self.terms[index];
                var insertion = index;
                while (insertion > 0 and termLessThan(
                    canonical_values,
                    term,
                    self.terms[insertion - 1],
                )) : (insertion -= 1) {
                    self.terms[insertion] = self.terms[insertion - 1];
                }
                self.terms[insertion] = term;
            }
        }
    };
    const AnalysisFactSet = struct {
        terms: [maximum_values * 3 + 1]InvariantTerm = undefined,
        len: usize = 0,

        fn contains(self: @This(), term: InvariantTerm) bool {
            for (self.terms[0..self.len]) |existing| {
                if (existing.eql(term)) return true;
            }
            return false;
        }

        fn insert(self: *@This(), term: InvariantTerm) Error!void {
            if (self.contains(term)) return;
            if (self.len == self.terms.len) {
                return error.TooManyInvariantTerms;
            }
            self.terms[self.len] = term;
            self.len += 1;
        }
    };
    const GeneratedFacts = struct {
        terms: AnalysisFactSet = .{},
        direct_len: usize = 0,
        direct_complete: bool = false,
    };

    return struct {
        const Self = @This();
        const CanonicalValueOrder = CanonicalValues;
        const InvariantFactSet = FactSet;
        const LiveValueSet = Set;

        constructors: [maximum_constructors]ConstructorType = undefined,
        constructor_count: usize = 0,
        entry_transitions: [maximum_blocks * 4]EntryTransition = undefined,
        entry_transition_count: usize = 0,

        fn definitionWitnesses(
            program: control_ir.Program,
            source_block: control_ir.Block,
            edge: control_ir.Edge,
            generated: GeneratedFacts,
            target_live: Set,
        ) Set {
            var required = Set.empty();
            for (generated.terms.terms[0..generated.direct_len]) |term| {
                term.addRequired(&required);
            }
            if (generated.terms.len <= generated.direct_len + 1) return required;
            const definitions = generated.terms.terms[generated.direct_len + 1 .. generated.terms.len];
            var future_dependent = Set.empty();
            for (definitions) |term| {
                var inputs = Set.empty();
                _ = term.addDefinitionInputs(&inputs);
                for (inputs.bits, 0..) |present, value_index| {
                    if (!present) continue;
                    const value: control_ir.ValueId = @intCast(value_index);
                    if (projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        false,
                        value,
                    ).len != 0) {
                        _ = future_dependent.insert(value);
                    }
                }
            }
            for (0..maximum_values) |_| {
                var changed = false;
                for (definitions) |term| {
                    const result = term.definitionResult() orelse continue;
                    var inputs = Set.empty();
                    _ = term.addDefinitionInputs(&inputs);
                    for (inputs.bits, 0..) |present, value_index| {
                        if (!present or
                            !future_dependent.bits[value_index]) continue;
                        changed = future_dependent.insert(result) or changed;
                        break;
                    }
                }
                if (!changed) break;
            }
            if (!generated.direct_complete) {
                switch (generated.terms.terms[generated.direct_len]) {
                    .boolean => |path_fact| {
                        if (future_dependent.contains(path_fact.value)) {
                            _ = required.insert(path_fact.value);
                        }
                    },
                    else => unreachable,
                }
            }
            for (definitions) |term| {
                const result = term.definitionResult() orelse continue;
                if (projectValues(
                    program,
                    source_block,
                    edge,
                    target_live,
                    false,
                    result,
                ).len != 0) {
                    _ = required.insert(result);
                }
            }
            for (0..maximum_values) |_| {
                var changed = false;
                for (definitions) |term| {
                    const result = term.definitionResult() orelse continue;
                    if (!required.contains(result)) continue;
                    changed = term.addDefinitionInputs(&required) or changed;
                }
                if (!changed) break;
            }
            return required;
        }

        /// Borrow all synthesized constructors in canonical id order.
        pub fn constructorSlice(self: *const Self) []const ConstructorType {
            return self.constructors[0..self.constructor_count];
        }

        /// Borrow the canonical Control IR edge-to-constructor mapping.
        pub fn entryTransitionSlice(self: *const Self) []const EntryTransition {
            return self.entry_transitions[0..self.entry_transition_count];
        }

        fn equivalent(
            left: *const ConstructorType,
            right: *const ConstructorType,
        ) bool {
            if (left.kind != right.kind or
                left.origin != right.origin or
                left.source_block != right.source_block or
                left.resume_target != right.resume_target or
                left.has_activation_context != right.has_activation_context or
                left.activation_len != right.activation_len or
                left.environment_len != right.environment_len or
                left.invariant_len != right.invariant_len)
            {
                return false;
            }
            for (
                left.activationFields(),
                right.activationFields(),
            ) |left_field, right_field| {
                if (left_field.value != right_field.value or
                    !left_field.value_type.eql(right_field.value_type))
                {
                    return false;
                }
            }
            for (
                left.environmentFields(),
                right.environmentFields(),
            ) |left_field, right_field| {
                if (left_field.value != right_field.value or
                    !left_field.value_type.eql(right_field.value_type))
                {
                    return false;
                }
            }
            for (
                left.invariantTerms(),
                right.invariantTerms(),
            ) |left_term, right_term| {
                if (!left_term.eql(right_term)) return false;
            }
            return true;
        }

        fn appendConstructor(
            self: *Self,
            program: control_ir.Program,
            constant_values: []const ?InvariantValue,
            kind: ConstructorKind,
            origin: ConstructorOrigin,
            source_block: control_ir.BlockId,
            resume_target: ?control_ir.BlockId,
            environment_set: Set,
            invariants: FactSet,
            canonical_values: CanonicalValues,
            liveness: Liveness,
        ) Error!u32 {
            var constructor: ConstructorType = .{
                .id = @intCast(self.constructor_count),
                .kind = kind,
                .origin = origin,
                .source_block = source_block,
                .resume_target = resume_target,
            };
            var required = environment_set;
            var ordered_invariants = invariants;
            try addEnvironmentDefinitions(
                program,
                constant_values,
                &required,
                &ordered_invariants,
            );
            ordered_invariants.canonicalize(canonical_values);
            if (comptime maximum_invariant_terms == 0) {
                if (ordered_invariants.len != 0) {
                    return error.TooManyInvariantTerms;
                }
            } else {
                for (ordered_invariants.terms[0..ordered_invariants.len]) |term| {
                    term.addRequired(&required);
                    constructor.invariants[constructor.invariant_len] = term;
                    constructor.invariant_len += 1;
                }
            }

            const source_function = program.blocks[
                @intCast(source_block)
            ].function_id;
            if (source_function != 0) {
                constructor.has_activation_context = true;
                if (comptime maximum_environment_fields == 0) {
                    return error.TooManyEnvironmentFields;
                }
                var function_entry: control_ir.BlockId = undefined;
                for (program.functions) |function| {
                    if (function.id == source_function) {
                        function_entry = function.entry;
                        break;
                    }
                } else return error.InvalidFunction;
                const entry = program.blocks[@intCast(function_entry)];
                for (canonical_values.values[0..canonical_values.len]) |value| {
                    if (!liveness.entry_live[@intCast(function_entry)].contains(value)) {
                        continue;
                    }
                    var is_entry_parameter = false;
                    for (entry.parameters) |parameter| {
                        if (parameter == value) {
                            is_entry_parameter = true;
                            break;
                        }
                    }
                    if (!is_entry_parameter) continue;
                    if (constructor.activation_len + 1 >=
                        maximum_environment_fields)
                    {
                        return error.TooManyEnvironmentFields;
                    }
                    constructor.activation[constructor.activation_len] = .{
                        .value = value,
                        .value_type = program.value_types[@intCast(value)],
                    };
                    constructor.activation_len += 1;
                }
            }
            for (canonical_values.values[0..canonical_values.len]) |value| {
                if (!required.contains(value)) continue;
                var activation_owned = false;
                for (constructor.activationFields()) |field| {
                    if (field.value == value) {
                        activation_owned = true;
                        break;
                    }
                }
                if (constructor.origin == .call_entry and activation_owned) {
                    continue;
                }
                if (comptime maximum_environment_fields == 0) {
                    return error.TooManyEnvironmentFields;
                }
                const activation_count = if (constructor.has_activation_context)
                    constructor.activation_len + 1
                else
                    0;
                if (constructor.environment_len + activation_count ==
                    maximum_environment_fields)
                {
                    return error.TooManyEnvironmentFields;
                }
                constructor.environment[constructor.environment_len] = .{
                    .value = value,
                    .value_type = program.value_types[@intCast(value)],
                };
                constructor.environment_len += 1;
            }
            for (self.constructorSlice()) |*existing| {
                if (equivalent(existing, &constructor)) return existing.id;
            }
            if (self.constructor_count == maximum_constructors) {
                return error.TooManyConstructors;
            }
            self.constructors[self.constructor_count] = constructor;
            self.constructor_count += 1;
            return constructor.id;
        }

        fn appendEntryTransition(
            self: *Self,
            source_block: control_ir.BlockId,
            edge_kind: IncomingEdgeKind,
            target_block: control_ir.BlockId,
            constructor_id: u32,
        ) Error!void {
            for (self.entryTransitionSlice()) |existing| {
                if (existing.source_block == source_block and
                    existing.edge_kind == edge_kind and
                    existing.target_block == target_block)
                {
                    if (existing.constructor_id != constructor_id) {
                        return error.UnsupportedInvariantDefinition;
                    }
                    return;
                }
            }
            if (self.entry_transition_count == self.entry_transitions.len) {
                return error.TooManyConstructors;
            }
            self.entry_transitions[self.entry_transition_count] = .{
                .source_block = source_block,
                .edge_kind = edge_kind,
                .target_block = target_block,
                .constructor_id = constructor_id,
            };
            self.entry_transition_count += 1;
        }

        const Projection = struct {
            values: [maximum_values]control_ir.ValueId = undefined,
            len: usize = 0,

            fn insert(self: *@This(), value: control_ir.ValueId) void {
                for (self.values[0..self.len]) |existing| {
                    if (existing == value) return;
                }
                self.values[self.len] = value;
                self.len += 1;
            }

            fn slice(self: *const @This()) []const control_ir.ValueId {
                return self.values[0..self.len];
            }
        };

        fn instructionResultTerm(
            result: control_ir.ValueId,
            definition: control_ir.ValueId,
            operands: []const control_ir.ValueId,
        ) Error!InvariantTerm {
            if (operands.len > maximum_executable_definition_operands) {
                return error.UnsupportedInvariantDefinition;
            }
            var stored_operands =
                [_]control_ir.ValueId{0} **
                maximum_executable_definition_operands;
            @memcpy(stored_operands[0..operands.len], operands);
            return .{ .instruction_result = .{
                .result = result,
                .definition = definition,
                .operand_count = @intCast(operands.len),
                .operands = stored_operands,
            } };
        }

        fn insertProjectedInstructionResult(
            result: *FactSet,
            result_value: control_ir.ValueId,
            definition: control_ir.ValueId,
            projections: *const [maximum_executable_definition_operands]Projection,
            operand_count: usize,
            operand_index: usize,
            selected: *[maximum_executable_definition_operands]control_ir.ValueId,
        ) Error!void {
            if (operand_index == operand_count) {
                try result.insert(try instructionResultTerm(
                    result_value,
                    definition,
                    selected[0..operand_count],
                ));
                return;
            }
            for (projections[operand_index].slice()) |operand| {
                selected[operand_index] = operand;
                try insertProjectedInstructionResult(
                    result,
                    result_value,
                    definition,
                    projections,
                    operand_count,
                    operand_index + 1,
                    selected,
                );
            }
        }

        fn canonicalDefinitionRoot(
            program: control_ir.Program,
            value: control_ir.ValueId,
        ) control_ir.ValueId {
            var root = value;
            for (0..maximum_values) |_| {
                const instruction = definingInstruction(program, root) orelse
                    break;
                if (instruction.operation != .copy or
                    instruction.operands.len != 1)
                {
                    break;
                }
                const source = instruction.operands[0];
                if (source == root) break;
                root = source;
            }
            return root;
        }

        fn projectValues(
            program: control_ir.Program,
            source_block: control_ir.Block,
            edge: control_ir.Edge,
            target_live: Set,
            retain_for_invariant: bool,
            value: control_ir.ValueId,
        ) Projection {
            var result: Projection = .{};
            var rebound = false;
            const canonical_value = canonicalDefinitionRoot(program, value);
            const target = program.blocks[@intCast(edge.target)];
            for (edge.arguments, target.parameters) |argument, parameter| {
                switch (argument) {
                    .value => |argument_value| {
                        if (canonicalDefinitionRoot(
                            program,
                            argument_value,
                        ) == canonical_value) {
                            rebound = true;
                            if (retain_for_invariant or
                                target_live.contains(parameter))
                            {
                                result.insert(parameter);
                            }
                        }
                    },
                    .@"resume" => {},
                }
            }
            for (target.parameters) |parameter| {
                if (parameter == value) return result;
            }
            if (source_block.function_id == target.function_id and
                (target_live.contains(value) or
                    (retain_for_invariant and !rebound)))
            {
                result.insert(value);
            }
            return result;
        }

        fn projectTermInto(
            program: control_ir.Program,
            source_block: control_ir.Block,
            edge: control_ir.Edge,
            target_live: Set,
            retain_for_invariant: bool,
            term: InvariantTerm,
            result: *FactSet,
        ) Error!void {
            switch (term) {
                .boolean => |predicate| {
                    const values = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        predicate.value,
                    );
                    for (values.slice()) |value| try result.insert(.{
                        .boolean = .{
                            .value = value,
                            .expected = predicate.expected,
                        },
                    });
                },
                .boolean_copy => |definition| {
                    const results = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.result,
                    );
                    const sources = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.source,
                    );
                    for (results.slice()) |result_value| {
                        for (sources.slice()) |source| {
                            if (result_value == source) continue;
                            try result.insert(.{ .boolean_copy = .{
                                .result = result_value,
                                .source = source,
                            } });
                        }
                    }
                },
                .boolean_not => |definition| {
                    const results = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.result,
                    );
                    const operands = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.operand,
                    );
                    for (results.slice()) |result_value| {
                        for (operands.slice()) |operand| try result.insert(.{
                            .boolean_not = .{
                                .result = result_value,
                                .operand = operand,
                            },
                        });
                    }
                },
                .boolean_binary => |definition| {
                    const results = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.result,
                    );
                    const left_values = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.left,
                    );
                    const right_values = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.right,
                    );
                    for (results.slice()) |result_value| {
                        for (left_values.slice()) |left| {
                            for (right_values.slice()) |right| {
                                try result.insert(.{ .boolean_binary = .{
                                    .result = result_value,
                                    .left = left,
                                    .right = right,
                                    .operation = definition.operation,
                                } });
                            }
                        }
                    }
                },
                .boolean_select => |definition| {
                    const results = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.result,
                    );
                    const conditions = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.condition,
                    );
                    const then_values = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.then_value,
                    );
                    const else_values = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.else_value,
                    );
                    for (results.slice()) |result_value| {
                        for (conditions.slice()) |condition| {
                            for (then_values.slice()) |then_value| {
                                for (else_values.slice()) |else_value| {
                                    try result.insert(.{ .boolean_select = .{
                                        .result = result_value,
                                        .condition = condition,
                                        .then_value = then_value,
                                        .else_value = else_value,
                                    } });
                                }
                            }
                        }
                    }
                },
                .value_copy => |definition| {
                    const results = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.result,
                    );
                    const sources = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.source,
                    );
                    for (results.slice()) |result_value| {
                        for (sources.slice()) |source| {
                            if (result_value == source) continue;
                            try result.insert(.{ .value_copy = .{
                                .result = result_value,
                                .source = source,
                            } });
                        }
                    }
                },
                .value_constant => |definition| {
                    const results = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.result,
                    );
                    for (results.slice()) |result_value| try result.insert(.{
                        .value_constant = .{
                            .result = result_value,
                            .contents = definition.contents,
                        },
                    });
                },
                .value_select => |definition| {
                    const results = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.result,
                    );
                    const conditions = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.condition,
                    );
                    const then_values = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.then_value,
                    );
                    const else_values = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.else_value,
                    );
                    for (results.slice()) |result_value| {
                        for (conditions.slice()) |condition| {
                            for (then_values.slice()) |then_value| {
                                for (else_values.slice()) |else_value| {
                                    try result.insert(.{ .value_select = .{
                                        .result = result_value,
                                        .condition = condition,
                                        .then_value = then_value,
                                        .else_value = else_value,
                                    } });
                                }
                            }
                        }
                    }
                },
                .instruction_result => |definition| {
                    const results = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.result,
                    );
                    var operands =
                        [_]Projection{.{}} **
                        maximum_executable_definition_operands;
                    for (
                        definition.operands[0..definition.operand_count],
                        0..,
                    ) |operand, operand_index| {
                        operands[operand_index] = projectValues(
                            program,
                            source_block,
                            edge,
                            target_live,
                            true,
                            operand,
                        );
                    }
                    var selected =
                        [_]control_ir.ValueId{0} **
                        maximum_executable_definition_operands;
                    for (results.slice()) |result_value| {
                        try insertProjectedInstructionResult(
                            result,
                            result_value,
                            definition.definition,
                            &operands,
                            definition.operand_count,
                            0,
                            &selected,
                        );
                    }
                },
                .product_extract_result => |definition| {
                    const results = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.result,
                    );
                    const products = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.product,
                    );
                    for (results.slice()) |result_value| {
                        for (products.slice()) |product| try result.insert(.{
                            .product_extract_result = .{
                                .result = result_value,
                                .product = product,
                                .field_index = definition.field_index,
                            },
                        });
                    }
                },
                .sum_extract_result => |definition| {
                    const results = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.result,
                    );
                    const sums = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.sum,
                    );
                    for (results.slice()) |result_value| {
                        for (sums.slice()) |sum| try result.insert(.{
                            .sum_extract_result = .{
                                .result = result_value,
                                .sum = sum,
                                .case_index = definition.case_index,
                            },
                        });
                    }
                },
                .bounded_length_result => |definition| {
                    const results = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.result,
                    );
                    const bounded_values = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.bounded,
                    );
                    for (results.slice()) |result_value| {
                        for (bounded_values.slice()) |bounded| try result.insert(.{
                            .bounded_length_result = .{
                                .result = result_value,
                                .bounded = bounded,
                            },
                        });
                    }
                },
                .integer_unary_result => |definition| {
                    const results = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.result,
                    );
                    const operands = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.operand,
                    );
                    for (results.slice()) |result_value| {
                        for (operands.slice()) |operand| try result.insert(.{
                            .integer_unary_result = .{
                                .result = result_value,
                                .operand = operand,
                                .operation = definition.operation,
                                .scalar_type = definition.scalar_type,
                            },
                        });
                    }
                },
                .integer_binary_result => |definition| {
                    const results = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.result,
                    );
                    const left_values = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.left,
                    );
                    const right_values = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.right,
                    );
                    for (results.slice()) |result_value| {
                        for (left_values.slice()) |left| {
                            for (right_values.slice()) |right| try result.insert(.{
                                .integer_binary_result = .{
                                    .result = result_value,
                                    .left = left,
                                    .right = right,
                                    .operation = definition.operation,
                                    .scalar_type = definition.scalar_type,
                                },
                            });
                        }
                    }
                },
                .integer_convert_result => |definition| {
                    const results = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.result,
                    );
                    const operands = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.operand,
                    );
                    for (results.slice()) |result_value| {
                        for (operands.slice()) |operand| try result.insert(.{
                            .integer_convert_result = .{
                                .result = result_value,
                                .operand = operand,
                                .scalar_type = definition.scalar_type,
                            },
                        });
                    }
                },
                .integer_zero => |predicate| {
                    const values = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        predicate.value,
                    );
                    for (values.slice()) |value| try result.insert(.{
                        .integer_zero = .{
                            .value = value,
                            .equal = predicate.equal,
                        },
                    });
                },
                .integer_zero_result => |definition| {
                    const results = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.result,
                    );
                    const values = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.value,
                    );
                    for (results.slice()) |result_value| {
                        for (values.slice()) |value| try result.insert(.{
                            .integer_zero_result = .{
                                .result = result_value,
                                .value = value,
                            },
                        });
                    }
                },
                .integer_relation => |predicate| {
                    const left_values = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        predicate.left,
                    );
                    const right_values = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        predicate.right,
                    );
                    for (left_values.slice()) |left| {
                        for (right_values.slice()) |right| try result.insert(.{
                            .integer_relation = .{
                                .left = left,
                                .right = right,
                                .relation = predicate.relation,
                                .expected = predicate.expected,
                            },
                        });
                    }
                },
                .integer_relation_result => |definition| {
                    const results = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.result,
                    );
                    const left_values = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.left,
                    );
                    const right_values = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.right,
                    );
                    for (results.slice()) |result_value| {
                        for (left_values.slice()) |left| {
                            for (right_values.slice()) |right| {
                                try result.insert(.{
                                    .integer_relation_result = .{
                                        .result = result_value,
                                        .left = left,
                                        .right = right,
                                        .relation = definition.relation,
                                    },
                                });
                            }
                        }
                    }
                },
                .sum_case => |predicate| {
                    const values = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        predicate.value,
                    );
                    for (values.slice()) |value| try result.insert(.{
                        .sum_case = .{
                            .value = value,
                            .case_index = predicate.case_index,
                            .equal = predicate.equal,
                        },
                    });
                },
                .sum_case_result => |definition| {
                    const results = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.result,
                    );
                    const values = projectValues(
                        program,
                        source_block,
                        edge,
                        target_live,
                        retain_for_invariant,
                        definition.value,
                    );
                    for (results.slice()) |result_value| {
                        for (values.slice()) |value| try result.insert(.{
                            .sum_case_result = .{
                                .result = result_value,
                                .value = value,
                                .case_index = definition.case_index,
                            },
                        });
                    }
                },
            }
        }

        fn addAnalysisInstructionDefinition(
            program: control_ir.Program,
            value: control_ir.ValueId,
            result_value: control_ir.ValueId,
            facts: *AnalysisFactSet,
            visited: *Set,
        ) Error!void {
            if (!visited.insert(value)) return;
            const instruction = definingInstruction(program, value) orelse
                return;
            if (instruction.kind == .pure and
                instruction.operation == .metadata)
            {
                return error.UnsupportedInvariantDefinition;
            }
            for (instruction.operands) |operand| {
                try addAnalysisInstructionDefinition(
                    program,
                    operand,
                    operand,
                    facts,
                    visited,
                );
            }
            try facts.insert(try instructionResultTerm(
                result_value,
                value,
                instruction.operands,
            ));
        }

        fn collectBooleanDefinitions(
            program: control_ir.Program,
            constant_values: []const ?InvariantValue,
            value: control_ir.ValueId,
            facts: *AnalysisFactSet,
            visited: *Set,
        ) Error!void {
            if (!visited.insert(value)) return;
            const instruction = definingInstruction(program, value) orelse
                return;
            if (instruction.kind == .compare_eq_zero and
                instruction.operands.len == 1)
            {
                try facts.insert(.{ .integer_zero_result = .{
                    .result = value,
                    .value = instruction.operands[0],
                } });
                var definition_visited = Set.empty();
                _ = try collectValueDefinition(
                    program,
                    constant_values,
                    instruction.operands[0],
                    facts,
                    &definition_visited,
                );
                return;
            }
            switch (instruction.operation) {
                .constant => {
                    if (value >= constant_values.len) {
                        return error.UnsupportedInvariantDefinition;
                    }
                    const contents = constant_values[@intCast(value)] orelse
                        return error.UnsupportedInvariantDefinition;
                    switch (contents) {
                        .boolean => {},
                        else => return error.UnsupportedInvariantDefinition,
                    }
                    try facts.insert(.{ .value_constant = .{
                        .result = value,
                        .contents = contents,
                    } });
                },
                .copy => {
                    try facts.insert(.{ .boolean_copy = .{
                        .result = value,
                        .source = instruction.operands[0],
                    } });
                    try collectBooleanDefinitions(
                        program,
                        constant_values,
                        instruction.operands[0],
                        facts,
                        visited,
                    );
                },
                .boolean_not => {
                    try facts.insert(.{ .boolean_not = .{
                        .result = value,
                        .operand = instruction.operands[0],
                    } });
                    try collectBooleanDefinitions(
                        program,
                        constant_values,
                        instruction.operands[0],
                        facts,
                        visited,
                    );
                },
                .boolean_and, .boolean_or => {
                    try facts.insert(.{ .boolean_binary = .{
                        .result = value,
                        .left = instruction.operands[0],
                        .right = instruction.operands[1],
                        .operation = if (instruction.operation == .boolean_and)
                            .@"and"
                        else
                            .@"or",
                    } });
                    try collectBooleanDefinitions(
                        program,
                        constant_values,
                        instruction.operands[0],
                        facts,
                        visited,
                    );
                    try collectBooleanDefinitions(
                        program,
                        constant_values,
                        instruction.operands[1],
                        facts,
                        visited,
                    );
                },
                .select => {
                    try facts.insert(.{ .boolean_select = .{
                        .result = value,
                        .condition = instruction.operands[0],
                        .then_value = instruction.operands[1],
                        .else_value = instruction.operands[2],
                    } });
                    for (instruction.operands) |operand| {
                        try collectBooleanDefinitions(
                            program,
                            constant_values,
                            operand,
                            facts,
                            visited,
                        );
                    }
                },
                .integer_equal,
                .integer_not_equal,
                .integer_less_than,
                .integer_less_equal,
                .integer_greater_than,
                .integer_greater_equal,
                => {
                    try facts.insert(.{ .integer_relation_result = .{
                        .result = value,
                        .left = instruction.operands[0],
                        .right = instruction.operands[1],
                        .relation = switch (instruction.operation) {
                            .integer_equal => .equal,
                            .integer_not_equal => .not_equal,
                            .integer_less_than => .less_than,
                            .integer_less_equal => .less_equal,
                            .integer_greater_than => .greater_than,
                            .integer_greater_equal => .greater_equal,
                            else => unreachable,
                        },
                    } });
                    for (instruction.operands) |operand| {
                        var definition_visited = Set.empty();
                        _ = try collectValueDefinition(
                            program,
                            constant_values,
                            operand,
                            facts,
                            &definition_visited,
                        );
                    }
                },
                .sum_tag_is => |case_index| {
                    try facts.insert(.{ .sum_case_result = .{
                        .result = value,
                        .value = instruction.operands[0],
                        .case_index = case_index,
                    } });
                    var definition_visited = Set.empty();
                    _ = try collectValueDefinition(
                        program,
                        constant_values,
                        instruction.operands[0],
                        facts,
                        &definition_visited,
                    );
                },
                .optional_is_some => {
                    try facts.insert(.{ .sum_case_result = .{
                        .result = value,
                        .value = instruction.operands[0],
                        .case_index = 1,
                    } });
                    var definition_visited = Set.empty();
                    _ = try collectValueDefinition(
                        program,
                        constant_values,
                        instruction.operands[0],
                        facts,
                        &definition_visited,
                    );
                },
                else => {
                    var definition_visited = Set.empty();
                    try addAnalysisInstructionDefinition(
                        program,
                        value,
                        value,
                        facts,
                        &definition_visited,
                    );
                },
            }
        }

        fn collectValueDefinition(
            program: control_ir.Program,
            constant_values: []const ?InvariantValue,
            value: control_ir.ValueId,
            facts: *AnalysisFactSet,
            visited: *Set,
        ) Error!bool {
            if (!visited.insert(value)) return true;
            const instruction = definingInstruction(program, value) orelse
                return true;
            return switch (instruction.operation) {
                .copy => {
                    const rooted = try collectValueDefinition(
                        program,
                        constant_values,
                        instruction.operands[0],
                        facts,
                        visited,
                    );
                    if (rooted) try facts.insert(.{ .value_copy = .{
                        .result = value,
                        .source = instruction.operands[0],
                    } });
                    return rooted;
                },
                .constant => {
                    if (value >= constant_values.len) {
                        return error.UnsupportedInvariantDefinition;
                    }
                    if (constant_values[@intCast(value)]) |contents| {
                        try facts.insert(.{ .value_constant = .{
                            .result = value,
                            .contents = contents,
                        } });
                    } else {
                        var definition_visited = Set.empty();
                        try addAnalysisInstructionDefinition(
                            program,
                            value,
                            value,
                            facts,
                            &definition_visited,
                        );
                    }
                    return true;
                },
                .integer_add,
                .integer_subtract,
                .integer_multiply,
                .integer_divide,
                .integer_remainder,
                .integer_bit_and,
                .integer_bit_or,
                .integer_bit_xor,
                => {
                    const scalar_type = switch (try program.valueType(value)) {
                        .scalar => |scalar| scalar,
                        .schema => return error.UnsupportedInvariantDefinition,
                    };
                    if (!scalar_type.isInteger()) {
                        return error.UnsupportedInvariantDefinition;
                    }
                    try facts.insert(.{ .integer_binary_result = .{
                        .result = value,
                        .left = instruction.operands[0],
                        .right = instruction.operands[1],
                        .operation = switch (instruction.operation) {
                            .integer_add => .add,
                            .integer_subtract => .subtract,
                            .integer_multiply => .multiply,
                            .integer_divide => .divide,
                            .integer_remainder => .remainder,
                            .integer_bit_and => .bit_and,
                            .integer_bit_or => .bit_or,
                            .integer_bit_xor => .bit_xor,
                            else => unreachable,
                        },
                        .scalar_type = scalar_type,
                    } });
                    for (instruction.operands) |operand| {
                        if (!try collectValueDefinition(
                            program,
                            constant_values,
                            operand,
                            facts,
                            visited,
                        )) return error.UnsupportedInvariantDefinition;
                    }
                    return true;
                },
                .integer_negate, .integer_bit_not => {
                    const scalar_type = switch (try program.valueType(value)) {
                        .scalar => |scalar| scalar,
                        .schema => return error.UnsupportedInvariantDefinition,
                    };
                    if (!scalar_type.isInteger()) {
                        return error.UnsupportedInvariantDefinition;
                    }
                    try facts.insert(.{ .integer_unary_result = .{
                        .result = value,
                        .operand = instruction.operands[0],
                        .operation = if (instruction.operation == .integer_negate)
                            .negate
                        else
                            .bit_not,
                        .scalar_type = scalar_type,
                    } });
                    if (!try collectValueDefinition(
                        program,
                        constant_values,
                        instruction.operands[0],
                        facts,
                        visited,
                    )) return error.UnsupportedInvariantDefinition;
                    return true;
                },
                .integer_convert => {
                    const scalar_type = switch (try program.valueType(value)) {
                        .scalar => |scalar| scalar,
                        .schema => return error.UnsupportedInvariantDefinition,
                    };
                    if (!scalar_type.isInteger()) {
                        return error.UnsupportedInvariantDefinition;
                    }
                    try facts.insert(.{ .integer_convert_result = .{
                        .result = value,
                        .operand = instruction.operands[0],
                        .scalar_type = scalar_type,
                    } });
                    if (!try collectValueDefinition(
                        program,
                        constant_values,
                        instruction.operands[0],
                        facts,
                        visited,
                    )) return error.UnsupportedInvariantDefinition;
                    return true;
                },
                .select => {
                    try facts.insert(.{ .value_select = .{
                        .result = value,
                        .condition = instruction.operands[0],
                        .then_value = instruction.operands[1],
                        .else_value = instruction.operands[2],
                    } });
                    var boolean_visited = Set.empty();
                    try collectBooleanDefinitions(
                        program,
                        constant_values,
                        instruction.operands[0],
                        facts,
                        &boolean_visited,
                    );
                    for (instruction.operands[1..]) |operand| {
                        if (!try collectValueDefinition(
                            program,
                            constant_values,
                            operand,
                            facts,
                            visited,
                        )) return error.UnsupportedInvariantDefinition;
                    }
                    return true;
                },
                .sum_construct => |case_index| {
                    if (instruction.operands.len == 0) {
                        try facts.insert(.{ .value_constant = .{
                            .result = value,
                            .contents = .{ .sum_case = case_index },
                        } });
                    } else {
                        var definition_visited = Set.empty();
                        try addAnalysisInstructionDefinition(
                            program,
                            value,
                            value,
                            facts,
                            &definition_visited,
                        );
                    }
                    return true;
                },
                .optional_none => {
                    try facts.insert(.{ .value_constant = .{
                        .result = value,
                        .contents = .{ .sum_case = 0 },
                    } });
                    return true;
                },
                .optional_some => {
                    var definition_visited = Set.empty();
                    try addAnalysisInstructionDefinition(
                        program,
                        value,
                        value,
                        facts,
                        &definition_visited,
                    );
                    return true;
                },
                .product_extract => |field_index| {
                    try facts.insert(.{ .product_extract_result = .{
                        .result = value,
                        .product = instruction.operands[0],
                        .field_index = field_index,
                    } });
                    if (!try collectValueDefinition(
                        program,
                        constant_values,
                        instruction.operands[0],
                        facts,
                        visited,
                    )) return error.UnsupportedInvariantDefinition;
                    return true;
                },
                .sum_extract => |case_index| {
                    try facts.insert(.{ .sum_extract_result = .{
                        .result = value,
                        .sum = instruction.operands[0],
                        .case_index = case_index,
                    } });
                    if (!try collectValueDefinition(
                        program,
                        constant_values,
                        instruction.operands[0],
                        facts,
                        visited,
                    )) return error.UnsupportedInvariantDefinition;
                    return true;
                },
                .vector_length, .text_length, .bytes_length => {
                    try facts.insert(.{ .bounded_length_result = .{
                        .result = value,
                        .bounded = instruction.operands[0],
                    } });
                    if (!try collectValueDefinition(
                        program,
                        constant_values,
                        instruction.operands[0],
                        facts,
                        visited,
                    )) return error.UnsupportedInvariantDefinition;
                    return true;
                },
                else => {
                    var definition_visited = Set.empty();
                    try addAnalysisInstructionDefinition(
                        program,
                        value,
                        value,
                        facts,
                        &definition_visited,
                    );
                    return true;
                },
            };
        }

        fn addInstructionDefinition(
            program: control_ir.Program,
            value: control_ir.ValueId,
            result_value: control_ir.ValueId,
            environment: *Set,
            facts: *FactSet,
            visited: *Set,
        ) Error!void {
            if (!visited.insert(value)) return;
            const instruction = definingInstruction(program, value) orelse
                return;
            if (instruction.kind == .pure and
                instruction.operation == .metadata)
            {
                return error.UnsupportedInvariantDefinition;
            }
            for (instruction.operands) |operand| {
                _ = environment.insert(operand);
                try addInstructionDefinition(
                    program,
                    operand,
                    operand,
                    environment,
                    facts,
                    visited,
                );
            }
            try facts.insert(try instructionResultTerm(
                result_value,
                value,
                instruction.operands,
            ));
        }

        fn addEnvironmentDefinitions(
            program: control_ir.Program,
            constant_values: []const ?InvariantValue,
            environment: *Set,
            facts: *FactSet,
        ) Error!void {
            const original = environment.*;
            var representable: AnalysisFactSet = .{};
            for (original.bits, 0..) |present, value_index| {
                if (!present) continue;
                const value: control_ir.ValueId = @intCast(value_index);
                switch (try program.valueType(value)) {
                    .scalar => |scalar| if (scalar == .boolean) {
                        var boolean_visited = Set.empty();
                        collectBooleanDefinitions(
                            program,
                            constant_values,
                            value,
                            &representable,
                            &boolean_visited,
                        ) catch continue;
                    } else {
                        var value_visited = Set.empty();
                        _ = collectValueDefinition(
                            program,
                            constant_values,
                            value,
                            &representable,
                            &value_visited,
                        ) catch continue;
                    },
                    .schema => {
                        var value_visited = Set.empty();
                        _ = collectValueDefinition(
                            program,
                            constant_values,
                            value,
                            &representable,
                            &value_visited,
                        ) catch continue;
                    },
                }
            }
            for (representable.terms[0..representable.len]) |term| {
                try facts.insert(term);
            }
            var visited = Set.empty();
            for (original.bits, 0..) |present, value_index| {
                if (!present) continue;
                const value: control_ir.ValueId = @intCast(value_index);
                var has_definition = false;
                for (representable.terms[0..representable.len]) |term| {
                    if (term.definitionResult() == value) {
                        has_definition = true;
                        break;
                    }
                }
                if (has_definition) continue;
                try addInstructionDefinition(
                    program,
                    value,
                    value,
                    environment,
                    facts,
                    &visited,
                );
            }
        }

        fn addTargetEdgeDefinitions(
            program: control_ir.Program,
            constant_values: []const ?InvariantValue,
            source_block: control_ir.Block,
            edge: control_ir.Edge,
            target_live: Set,
            facts: *FactSet,
        ) Error!void {
            const target = program.blocks[@intCast(edge.target)];
            for (target.parameters, edge.arguments) |parameter, argument| {
                if (!target_live.contains(parameter)) continue;
                switch (argument) {
                    .value => |source| {
                        const canonical_source = canonicalDefinitionRoot(
                            program,
                            source,
                        );
                        var representable: AnalysisFactSet = .{};
                        var definition_visited = Set.empty();
                        const has_definition =
                            definingInstruction(program, canonical_source) != null;
                        const definition_complete = if (has_definition)
                            collectValueDefinition(
                                program,
                                constant_values,
                                canonical_source,
                                &representable,
                                &definition_visited,
                            ) catch false
                        else
                            false;
                        if (definition_complete and representable.len != 0) {
                            for (representable.terms[0..representable.len]) |term| {
                                try projectTermInto(
                                    program,
                                    source_block,
                                    edge,
                                    target_live,
                                    true,
                                    term,
                                    facts,
                                );
                            }
                            continue;
                        }
                        if (has_definition) {
                            var executable_visited = Set.empty();
                            var retained = target_live;
                            try addInstructionDefinition(
                                program,
                                canonical_source,
                                parameter,
                                &retained,
                                facts,
                                &executable_visited,
                            );
                        }
                    },
                    .@"resume" => {},
                }
            }
        }

        fn collectDirectBranchFacts(
            program: control_ir.Program,
            value: control_ir.ValueId,
            expected: bool,
            facts: *AnalysisFactSet,
            visited: *Set,
        ) Error!bool {
            if (!visited.insert(value)) return true;
            if (directFactForValue(
                program,
                value,
                expected,
                program.value_types.len + 1,
            )) |direct| {
                try facts.insert(direct);
            }

            const instruction = definingInstruction(program, value) orelse
                return false;
            return switch (instruction.operation) {
                .copy => try collectDirectBranchFacts(
                    program,
                    instruction.operands[0],
                    expected,
                    facts,
                    visited,
                ),
                .boolean_not => try collectDirectBranchFacts(
                    program,
                    instruction.operands[0],
                    !expected,
                    facts,
                    visited,
                ),
                .boolean_and => if (!expected)
                    false
                else blk: {
                    const left_complete = try collectDirectBranchFacts(
                        program,
                        instruction.operands[0],
                        true,
                        facts,
                        visited,
                    );
                    const right_complete = try collectDirectBranchFacts(
                        program,
                        instruction.operands[1],
                        true,
                        facts,
                        visited,
                    );
                    break :blk left_complete and right_complete;
                },
                .boolean_or => if (expected)
                    false
                else blk: {
                    const left_complete = try collectDirectBranchFacts(
                        program,
                        instruction.operands[0],
                        false,
                        facts,
                        visited,
                    );
                    const right_complete = try collectDirectBranchFacts(
                        program,
                        instruction.operands[1],
                        false,
                        facts,
                        visited,
                    );
                    break :blk left_complete and right_complete;
                },
                else => directFactForValue(
                    program,
                    value,
                    expected,
                    program.value_types.len + 1,
                ) != null,
            };
        }

        fn branchFacts(
            program: control_ir.Program,
            constant_values: []const ?InvariantValue,
            branch: control_ir.Branch,
            expected: bool,
        ) Error!GeneratedFacts {
            var result: GeneratedFacts = .{};
            var direct_visited = Set.empty();
            result.direct_complete = try collectDirectBranchFacts(
                program,
                branch.condition,
                expected,
                &result.terms,
                &direct_visited,
            );
            result.direct_len = result.terms.len;
            try result.terms.insert(.{ .boolean = .{
                .value = branch.condition,
                .expected = expected,
            } });
            var visited = Set.empty();
            try collectBooleanDefinitions(
                program,
                constant_values,
                branch.condition,
                &result.terms,
                &visited,
            );
            var direct_values = Set.empty();
            for (result.terms.terms[0..result.direct_len]) |term| {
                term.addRequired(&direct_values);
            }
            for (direct_values.bits, 0..) |present, value_index| {
                if (!present) continue;
                var definition_visited = Set.empty();
                _ = try collectValueDefinition(
                    program,
                    constant_values,
                    @intCast(value_index),
                    &result.terms,
                    &definition_visited,
                );
            }
            return result;
        }

        fn transferFacts(
            program: control_ir.Program,
            source_block: control_ir.Block,
            edge: control_ir.Edge,
            target_live: Set,
            source_facts: FactSet,
            generated: GeneratedFacts,
        ) Error!FactSet {
            var result: FactSet = .{};
            const definition_witnesses = definitionWitnesses(
                program,
                source_block,
                edge,
                generated,
                target_live,
            );
            for (source_facts.terms[0..source_facts.len]) |term| {
                try projectTermInto(
                    program,
                    source_block,
                    edge,
                    target_live,
                    false,
                    term,
                    &result,
                );
            }
            for (
                generated.terms.terms[0..generated.terms.len],
                0..,
            ) |term, index| {
                const retain_definition =
                    if (term.definitionResult()) |definition_result|
                        definition_witnesses.contains(definition_result)
                    else
                        false;
                const retain_for_invariant =
                    index < generated.direct_len or
                    (index == generated.direct_len and
                        !generated.direct_complete) or
                    (index > generated.direct_len and
                        retain_definition);
                try projectTermInto(
                    program,
                    source_block,
                    edge,
                    target_live,
                    retain_for_invariant,
                    term,
                    &result,
                );
            }
            return result;
        }

        fn meetIncoming(
            next: *FactSet,
            saw_predecessor: *bool,
            candidate: FactSet,
        ) void {
            if (!saw_predecessor.*) {
                next.* = candidate;
                saw_predecessor.* = true;
                return;
            }
            next.* = next.intersection(candidate);
        }

        fn considerEdge(
            program: control_ir.Program,
            constant_values: []const ?InvariantValue,
            source_block: control_ir.Block,
            source_facts: FactSet,
            edge: control_ir.Edge,
            target_live: Set,
            generated: GeneratedFacts,
            include_edge_definition: bool,
            target: control_ir.BlockId,
            next: *FactSet,
            saw_predecessor: *bool,
        ) Error!void {
            if (!edgeTargets(edge, target)) return;
            var candidate = try transferFacts(
                program,
                source_block,
                edge,
                target_live,
                source_facts,
                generated,
            );
            if (include_edge_definition) {
                try addTargetEdgeDefinitions(
                    program,
                    constant_values,
                    source_block,
                    edge,
                    target_live,
                    &candidate,
                );
            }
            meetIncoming(next, saw_predecessor, candidate);
        }

        fn incomingFacts(
            program: control_ir.Program,
            constant_values: []const ?InvariantValue,
            reachability: ReachabilityType,
            liveness: Liveness,
            current: [maximum_blocks]FactSet,
            initialized: [maximum_blocks]bool,
            target: control_ir.BlockId,
        ) Error!?FactSet {
            var next: FactSet = .{};
            var saw_predecessor = false;
            for (program.blocks) |source_block| {
                if (!reachability.contains(source_block.id) or
                    !initialized[@intCast(source_block.id)])
                {
                    continue;
                }
                const source_facts = current[@intCast(source_block.id)];
                switch (source_block.terminator) {
                    .jump => |edge| try considerEdge(
                        program,
                        constant_values,
                        source_block,
                        source_facts,
                        edge,
                        liveness.entry_live[@intCast(target)],
                        .{},
                        true,
                        target,
                        &next,
                        &saw_predecessor,
                    ),
                    .branch => |branch| {
                        const then_facts = try branchFacts(
                            program,
                            constant_values,
                            branch,
                            true,
                        );
                        const else_facts = try branchFacts(
                            program,
                            constant_values,
                            branch,
                            false,
                        );
                        try considerEdge(
                            program,
                            constant_values,
                            source_block,
                            source_facts,
                            branch.then_edge,
                            liveness.entry_live[@intCast(target)],
                            then_facts,
                            true,
                            target,
                            &next,
                            &saw_predecessor,
                        );
                        try considerEdge(
                            program,
                            constant_values,
                            source_block,
                            source_facts,
                            branch.else_edge,
                            liveness.entry_live[@intCast(target)],
                            else_facts,
                            true,
                            target,
                            &next,
                            &saw_predecessor,
                        );
                    },
                    .@"suspend" => |suspension| {
                        if (suspension.callee) |callee| {
                            try considerEdge(
                                program,
                                constant_values,
                                source_block,
                                source_facts,
                                callee,
                                liveness.entry_live[@intCast(target)],
                                .{},
                                false,
                                target,
                                &next,
                                &saw_predecessor,
                            );
                        }
                        try considerEdge(
                            program,
                            constant_values,
                            source_block,
                            source_facts,
                            suspension.continuation,
                            liveness.entry_live[@intCast(target)],
                            .{},
                            true,
                            target,
                            &next,
                            &saw_predecessor,
                        );
                    },
                    .return_value, .return_to_caller, .fail, .fail_value => {},
                }
            }
            return if (saw_predecessor) next else null;
        }

        fn analyzePathFacts(
            program: control_ir.Program,
            constant_values: []const ?InvariantValue,
            reachability: ReachabilityType,
            liveness: Liveness,
        ) Error![maximum_blocks]FactSet {
            var result = [_]FactSet{.{}} ** maximum_blocks;
            var initialized = [_]bool{false} ** maximum_blocks;
            initialized[@intCast(program.entry)] = true;
            const maximum_iterations =
                program.blocks.len * (maximum_invariant_terms + 2) + 1;
            var iteration: usize = 0;
            while (iteration < maximum_iterations) : (iteration += 1) {
                var changed = false;
                var next = result;
                var next_initialized = initialized;
                for (program.blocks) |block| {
                    if (!reachability.contains(block.id) or
                        block.id == program.entry)
                    {
                        continue;
                    }
                    const facts = try incomingFacts(
                        program,
                        constant_values,
                        reachability,
                        liveness,
                        result,
                        initialized,
                        block.id,
                    ) orelse continue;
                    if (!next_initialized[@intCast(block.id)] or
                        !next[@intCast(block.id)].eql(facts))
                    {
                        next[@intCast(block.id)] = facts;
                        next_initialized[@intCast(block.id)] = true;
                        changed = true;
                    }
                }
                result = next;
                initialized = next_initialized;
                if (!changed) {
                    for (program.blocks) |block| {
                        if (reachability.contains(block.id) and
                            !initialized[@intCast(block.id)])
                        {
                            return error.PathFactsDidNotConverge;
                        }
                    }
                    return result;
                }
            }
            return error.PathFactsDidNotConverge;
        }

        fn appendIncomingConstructor(
            result: *Self,
            program: control_ir.Program,
            constant_values: []const ?InvariantValue,
            liveness: Liveness,
            path_facts: [maximum_blocks]FactSet,
            canonical_values: CanonicalValues,
            source_block: control_ir.Block,
            edge: control_ir.Edge,
            incoming_edge_kind: IncomingEdgeKind,
            generated: GeneratedFacts,
        ) Error!void {
            const target_index: usize = @intCast(edge.target);
            const environment = liveness.entry_live[target_index];
            var facts = try transferFacts(
                program,
                source_block,
                edge,
                environment,
                path_facts[@intCast(source_block.id)],
                generated,
            );
            if (incoming_edge_kind != .call) {
                try addTargetEdgeDefinitions(
                    program,
                    constant_values,
                    source_block,
                    edge,
                    environment,
                    &facts,
                );
            }
            const target = program.blocks[target_index];
            const constructor_id = try result.appendConstructor(
                program,
                constant_values,
                constructorKindForRole(target.role),
                if (incoming_edge_kind == .call)
                    .call_entry
                else
                    .block_entry,
                edge.target,
                edge.target,
                environment,
                facts,
                canonical_values,
                liveness,
            );
            try result.appendEntryTransition(
                source_block.id,
                incoming_edge_kind,
                edge.target,
                constructor_id,
            );
        }

        /// Synthesize entry, persisted block, and suspension constructors from
        /// one already computed root-reachable control graph.
        pub fn synthesizeReachable(
            program: control_ir.Program,
            reachability: ReachabilityType,
        ) Error!Self {
            const no_constants = [_]?InvariantValue{null} ** maximum_values;
            return synthesizeReachableWithConstants(
                program,
                reachability,
                &no_constants,
            );
        }

        /// Synthesize with compiler-owned scalar constant witnesses used only
        /// to authenticate direct constructor-local path facts.
        pub fn synthesizeReachableWithConstants(
            program: control_ir.Program,
            reachability: ReachabilityType,
            constant_values: []const ?InvariantValue,
        ) Error!Self {
            if (constant_values.len < program.value_types.len) {
                return error.UnsupportedInvariantDefinition;
            }
            const liveness = try Liveness.analyze(program);
            const path_facts = try analyzePathFacts(
                program,
                constant_values,
                reachability,
                liveness,
            );
            const canonical_values = CanonicalValues.analyze(
                program,
                reachability,
            );
            var result: Self = .{};
            const entry_index: usize = @intCast(program.entry);
            _ = try result.appendConstructor(
                program,
                constant_values,
                .entry,
                .block_entry,
                program.entry,
                program.entry,
                liveness.entry_live[entry_index],
                .{},
                canonical_values,
                liveness,
            );

            for (0..reachability.count) |dense_block_index| {
                const source_block = reachability.sourceId(
                    @intCast(dense_block_index),
                ) orelse unreachable;
                const block = program.blocks[@intCast(source_block)];
                const block_index: usize = @intCast(block.id);
                switch (block.terminator) {
                    .jump => |edge| try appendIncomingConstructor(
                        &result,
                        program,
                        constant_values,
                        liveness,
                        path_facts,
                        canonical_values,
                        block,
                        edge,
                        .jump,
                        .{},
                    ),
                    .branch => |branch| {
                        try appendIncomingConstructor(
                            &result,
                            program,
                            constant_values,
                            liveness,
                            path_facts,
                            canonical_values,
                            block,
                            branch.then_edge,
                            .branch_then,
                            try branchFacts(
                                program,
                                constant_values,
                                branch,
                                true,
                            ),
                        );
                        try appendIncomingConstructor(
                            &result,
                            program,
                            constant_values,
                            liveness,
                            path_facts,
                            canonical_values,
                            block,
                            branch.else_edge,
                            .branch_else,
                            try branchFacts(
                                program,
                                constant_values,
                                branch,
                                false,
                            ),
                        );
                    },
                    .@"suspend" => |suspension| {
                        if (suspension.callee) |callee| {
                            try appendIncomingConstructor(
                                &result,
                                program,
                                constant_values,
                                liveness,
                                path_facts,
                                canonical_values,
                                block,
                                callee,
                                .call,
                                .{},
                            );
                        }
                        const persists_continuation =
                            suspension.kind == .explicit_yield or
                            suspension.kind == .caller_fuel;
                        if (!persists_continuation) {
                            try appendIncomingConstructor(
                                &result,
                                program,
                                constant_values,
                                liveness,
                                path_facts,
                                canonical_values,
                                block,
                                suspension.continuation,
                                .suspension_continuation,
                                .{},
                            );
                        }
                        var environment = if (persists_continuation)
                            liveness.entry_live[suspension.continuation.target]
                        else
                            liveness.edgeEnvironment(
                                program,
                                suspension.continuation,
                            );
                        for (suspension.request_values) |value| {
                            _ = environment.insert(value);
                        }
                        if (suspension.callee) |callee| {
                            const callee_target = program.blocks[
                                @intCast(callee.target)
                            ];
                            for (
                                callee_target.parameters,
                                callee.arguments,
                            ) |parameter, argument| {
                                if (!liveness.entry_live[
                                    @intCast(callee.target)
                                ].contains(parameter)) continue;
                                switch (argument) {
                                    .value => |value| _ = environment.insert(value),
                                    .@"resume" => unreachable,
                                }
                            }
                        }
                        var suspension_facts = if (persists_continuation)
                            try transferFacts(
                                program,
                                block,
                                suspension.continuation,
                                environment,
                                path_facts[block_index],
                                .{},
                            )
                        else
                            path_facts[block_index];
                        if (persists_continuation) {
                            try addTargetEdgeDefinitions(
                                program,
                                constant_values,
                                block,
                                suspension.continuation,
                                environment,
                                &suspension_facts,
                            );
                        }
                        const constructor_id = try result.appendConstructor(
                            program,
                            constant_values,
                            constructorKindForSuspension(suspension.kind),
                            .suspension,
                            if (persists_continuation)
                                suspension.continuation.target
                            else
                                block.id,
                            suspension.continuation.target,
                            environment,
                            suspension_facts,
                            canonical_values,
                            liveness,
                        );
                        if (persists_continuation) {
                            try result.appendEntryTransition(
                                block.id,
                                .suspension_continuation,
                                suspension.continuation.target,
                                constructor_id,
                            );
                        }
                    },
                    .return_value, .return_to_caller, .fail, .fail_value => {},
                }
            }
            return result;
        }

        /// Synthesize from the root-reachable graph of one validated program.
        pub fn synthesize(program: control_ir.Program) Error!Self {
            const reachability = try ReachabilityType.analyze(program);
            return synthesizeReachable(program, reachability);
        }
    };
}

